#!/usr/bin/env node
// Derives snapshots/canon.data.js: everything the page and the tests read about Skyhook, wrapped
// as a classic script (window.SKYHOOK_CANON / module.exports) so index.html can read it when
// opened from file:// (fetch() of a sibling JSON file is blocked there). Nothing is retyped:
//
//  1. snapshots/rev_a.json  — parsed and re-serialised whole, with its provenance sidecar.
//  2. snapshots/skyhook_physics.py — three module constants regexed out of the snapshot COPY
//     (never out of the repo), with the line each sits on:  R_EARTH_KM, G_STD and the
//     `v_earth_rot = 0.465` literal of EQ-3a. The page's Earth radius and ground-relative
//     convention are pinned to these.
//  3. snapshots/golden.json — the twin's golden run: its meta, the t=0 state of the lower tip,
//     hub and upper tip nodes (rigid rotation, tether vertical), and the 600 s means. The
//     lower-tip state is the reconciliation pin for v_orb - v_tip at r_com - L.
//
// Everything is read from THIS folder, so the derived file can only disagree with the snapshots
// if one is edited by hand; catchwindow.test.mjs re-derives and compares.
//
//   node ideas/09-two-seconds-at-bottom/build-data.mjs           writes snapshots/canon.data.js
//   node ideas/09-two-seconds-at-bottom/build-data.mjs --check   exit 1 if the written file is stale
//
// After writing, record provenance with the bank's tool (the sidecar points at rev_a.json, the
// file most of the content comes from; the other two sources have their own sidecars):
//   node tools/snapshot.mjs /home/user/skyhook params/rev_a.json \
//     ideas/09-two-seconds-at-bottom/snapshots/canon.data.js --sidecar-only --note "derived by build-data.mjs: ..."
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const snap = (f) => path.join(here, 'snapshots', f);
const readJson = (f) => JSON.parse(fs.readFileSync(snap(f), 'utf8'));

// A module-level `NAME = <number>` assignment, or an indented `name = <number> if ...` literal,
// with the 1-based line it sits on. Throws if absent or ambiguous, so a changed module is noticed.
export function pyConstant(source, name) {
  const lines = source.split('\n');
  const re = new RegExp(`^\\s*${name}\\s*=\\s*(-?\\d+(?:\\.\\d+)?(?:[eE][-+]?\\d+)?)\\b`);
  const hits = [];
  lines.forEach((text, i) => {
    const m = re.exec(text);
    if (m) hits.push({ value: Number(m[1]), line: i + 1, text: text.trim() });
  });
  if (hits.length !== 1) throw new Error(`${name}: expected exactly one assignment in skyhook_physics.py, found ${hits.length}`);
  return hits[0];
}

export function derive() {
  const revA = readJson('rev_a.json');
  const revAProvenance = readJson('rev_a.json.provenance.json');
  const py = fs.readFileSync(snap('skyhook_physics.py'), 'utf8');
  const pyProvenance = readJson('skyhook_physics.py.provenance.json');
  const golden = readJson('golden.json');
  const goldenProvenance = readJson('golden.json.provenance.json');

  const n = golden.meta.config.n_nodes;
  const s0 = golden.checkpoints['0'].state;
  if (s0.length !== 4 * n) throw new Error(`golden t=0 state has ${s0.length} numbers, expected 4 × ${n}`);
  const node = (i) => s0.slice(4 * i, 4 * i + 4); // [x, y, vx, vy] in m and m/s (planar, inertial)

  return {
    revA,
    revAProvenance,
    physicsModule: {
      path: pyProvenance.path,
      commit: pyProvenance.commit,
      sourceSha256: pyProvenance.sourceSha256,
      R_EARTH_KM: pyConstant(py, 'R_EARTH_KM'),
      G_STD: pyConstant(py, 'G_STD'),
      v_earth_rot_kms: pyConstant(py, 'v_earth_rot'),
    },
    golden: {
      path: goldenProvenance.path,
      commit: goldenProvenance.commit,
      sourceSha256: goldenProvenance.sourceSha256,
      meta: golden.meta,
      t0: {
        lowerTip: node(0),
        hub: node((n - 1) / 2),
        upperTip: node(n - 1),
      },
      mean_tip_speed_mps: golden.mean_tip_speed_mps,
      mean_tip_centripetal_accel_mps2: golden.mean_tip_centripetal_accel_mps2,
    },
  };
}

export function render(d) {
  const body = JSON.stringify(d, null, 1).replace(/\n/g, '\n  ');
  return `// Generated by build-data.mjs from the files under snapshots/ and their provenance sidecars. Do not edit.
// Skyhook params/rev_a.json @ ${d.revAProvenance.commit} (sha256 ${d.revAProvenance.sourceSha256});
// physics/skyhook_physics.py and tools/twin/golden.json at the same commit (hashes inside).
(function (root, factory) {
  if (typeof module === 'object' && module.exports) module.exports = factory();
  else root.SKYHOOK_CANON = factory();
})(typeof self !== 'undefined' ? self : this, function () {
  return ${body};
});
`;
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const dest = snap('canon.data.js');
  const out = render(derive());
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(dest) ? fs.readFileSync(dest, 'utf8') : '';
    if (cur !== out) {
      console.error('canon.data.js is stale; re-run build-data.mjs');
      process.exit(1);
    }
    console.log('canon.data.js is current');
  } else {
    fs.writeFileSync(dest, out);
    console.log(`wrote ${path.relative(process.cwd(), dest)} (${out.length} bytes)`);
  }
}
