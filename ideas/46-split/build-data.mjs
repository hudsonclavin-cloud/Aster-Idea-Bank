  if (p.refusal) throw new Error('idea 45 refused idea 44\'s Bennu handoff: ' + p.refusal.reason);
  const R = L.K.run(p.src, {});
  if (R.refusal) throw new Error('idea 45 refused its Bennu case: ' + R.refusal.reason);
  const hbFull = JSON.parse(JSON.stringify(L.K.buildHandoff(R, '2026-11-01T12:00:00Z')));
  const hb = Split.pruneUpstream(hbFull);
  const back = L.K.parseHandoff(hbFull);
