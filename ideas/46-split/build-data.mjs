// Regenerates idea 46's derived snapshots. Nothing here is needed to run the page or the tests.
//
//   node ideas/46-split/build-data.mjs <dir from oracle/fetch-sources.sh>   writes snapshots/split-sources.js (+ sidecar):
//        every transcribed figure is checked against its source text (whitespace-normalised) and the NIST and
//        JANAF tables are parsed from the fetched files themselves
//   node ideas/46-split/build-data.mjs --partforge                          writes snapshots/partforge-materials.js and
//        snapshots/partforge-factor.js from the PartForge checkout (FLIGHT_MATERIALS metals, NASA-STD-5001B Table 1 row)
//   node ideas/46-split/build-data.mjs --handoffs                           writes snapshots/dig-handoff.js (idea 45's
//        committed handoff, wrapped) and snapshots/dig-bennu-handoff.js (idea 45's kernel run on its Bennu case)
//   node ideas/46-split/build-data.mjs --sample                             writes handoff.json (this page's defaults)
