const sha = (b) => crypto.createHash('sha256').update(b).digest('hex');

function wrap(name, comment, obj) {
  return '/* ' + comment + '\n * GENERATED by ideas/46-split/build-data.mjs; do not edit. Classic script (window.' + name + ') and require(). */\n' +
    '(function (root) {\n  var D = ' + JSON.stringify(obj) + ';\n  if (typeof module === \'object\' && module.exports) module.exports = D;\n  else root.' + name + ' = D;\n})(typeof self !== \'undefined\' ? self : this);\n';
}
function writeWithSidecar(rel, text, prov) {
  const p = path.join(HERE, rel);
  fs.writeFileSync(p, text);
  const b = fs.readFileSync(p);
  prov.writtenSha256 = sha(b);
  prov.writtenBytes = b.length;
  fs.writeFileSync(p + '.provenance.json', JSON.stringify(prov, null, 2) + '\n');
  console.log('wrote', rel, b.length, 'bytes');
}
function norm(buf, kind) {
  let t = buf.toString('utf8');
  if (kind === 'html' || kind === 'json') {
    t = t.replace(/<script[\s\S]*?<\/script>/gi, ' ').replace(/<style[\s\S]*?<\/style>/gi, ' ').replace(/<[^>]+>/g, ' ');
    t = t.replace(/&nbsp;/g, ' ').replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&#039;|&#39;|&rsquo;/g, "'").replace(/&quot;/g, '"').replace(/ /g, ' ');
  }
  return t.replace(/\s+/g, ' ');
}

