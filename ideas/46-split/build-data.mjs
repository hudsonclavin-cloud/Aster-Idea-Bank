// ------------------------------------------------------------------------------------------------ PartForge (source repo)
function buildPartforge() {
  const head = execFileSync('git', ['rev-parse', 'HEAD'], { cwd: PARTFORGE, encoding: 'utf8' }).trim();
  const html = fs.readFileSync(path.join(PARTFORGE, 'index.html'), 'utf8');
  const i0 = html.indexOf('const FLIGHT_MATERIALS = {');
  if (i0 < 0) throw new Error('FLIGHT_MATERIALS not found');
  let depth = 0, i = html.indexOf('{', i0), j = i;
  for (; j < html.length; j++) { const c = html[j]; if (c === '{') depth++; else if (c === '}') { depth--; if (depth === 0) break; } }
  const literal = html.slice(i, j + 1);
  const line = html.slice(0, i0).split('\n').length;
  // The literal is plain data (strings, numbers, booleans); evaluate it in an empty function scope.
  const all = new Function('return (' + literal + ');')();
  const keep = {};
  Object.keys(all).forEach((k) => { const m = all[k]; if (m.kind === 'metal') keep[k] = { name: m.name, den_g_cm3: m.den, sy_MPa: m.sy, su_MPa: m.su, src: m.src, verify: m.verify, note: m.note }; });
  const out = { cite: 'PartForge index.html FLIGHT_MATERIALS (line ' + line + ' at ' + head.slice(0, 7) + '): "typical room-temperature values (MatWeb / manufacturer datasheet class)"; verify:true marks entries that could not be confirmed against a live source', metals: keep };
  const p = 'snapshots/partforge-materials.js';
  fs.writeFileSync(path.join(HERE, p), wrap('SplitMaterials', 'PartForge\'s flight metals (density, yield, ultimate, source, verify flag), excerpted unmodified from FLIGHT_MATERIALS.', out));
  execFileSync(process.execPath, [path.join(BANK, 'tools/snapshot.mjs'), PARTFORGE, 'index.html', path.join(HERE, p), '--sidecar-only', '--note',
    'derived by build-data.mjs --partforge: the FLIGHT_MATERIALS object literal at index.html line ' + line + ', metals only (kind "metal"), fields den, sy, su, src, verify, note copied unmodified'], { stdio: 'inherit' });
  const df = JSON.parse(fs.readFileSync(path.join(PARTFORGE, 'data/tables/design_factors_nasa.json'), 'utf8'));
  const row = df.rows.find((r) => r.key === 'fos_metallic_prototype');
  const tank = df.rows.find((r) => r.key === 'proof_test_factor_tanks_srm');
  const p2 = 'snapshots/partforge-factor.js';
  fs.writeFileSync(path.join(HERE, p2), wrap('SplitFactor', 'PartForge\'s NASA-STD-5001B rows for metallic structure and propellant tanks, copied unmodified (with the table\'s license note).', { license_note: df.license_note, ultimate: row, tanks: tank }));
  execFileSync(process.execPath, [path.join(BANK, 'tools/snapshot.mjs'), PARTFORGE, 'data/tables/design_factors_nasa.json', path.join(HERE, p2), '--sidecar-only', '--note',
    'derived by build-data.mjs --partforge: rows fos_metallic_prototype and proof_test_factor_tanks_srm and the license_note, unmodified'], { stdio: 'inherit' });
}

