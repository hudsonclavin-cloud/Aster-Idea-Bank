#!/usr/bin/env node
// Wraps snapshots/rev_a.json and its provenance sidecar as a classic script (window.REV_A in the
// page, module.exports under Node) so index.html can read the canon when opened from file://,
// where fetch() of a sibling JSON file is blocked. Nothing is retyped: the JSON is parsed and
// re-serialised, and taper.test.mjs checks the result is deep-equal to snapshots/rev_a.json.
// After running it, record its provenance with
//   node tools/snapshot.mjs /home/user/skyhook params/rev_a.json \
//     ideas/15-taper-is-not-mass/snapshots/rev_a.data.js --sidecar-only --note "..."
// From the bank root: node ideas/15-taper-is-not-mass/build-data.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const src = path.join(here, 'snapshots', 'rev_a.json');
const side = path.join(here, 'snapshots', 'rev_a.json.provenance.json');
const dest = path.join(here, 'snapshots', 'rev_a.data.js');

const data = JSON.parse(fs.readFileSync(src, 'utf8'));
const provenance = JSON.parse(fs.readFileSync(side, 'utf8'));
const indent = (v) => JSON.stringify(v, null, 1).replace(/\n/g, '\n    ');
const out = `// Generated by build-data.mjs from snapshots/rev_a.json and its provenance sidecar. Do not edit.
// Skyhook params/rev_a.json @ ${provenance.commit} (sha256 ${provenance.sourceSha256}).
(function (root, factory) {
  if (typeof module === 'object' && module.exports) module.exports = factory();
  else root.REV_A = factory();
})(typeof self !== 'undefined' ? self : this, function () {
  return {
    data: ${indent(data)},
    provenance: ${indent(provenance)}
  };
});
`;
fs.writeFileSync(dest, out);
console.log(`wrote ${path.relative(process.cwd(), dest)} (${out.length} bytes) from ${provenance.path} @ ${String(provenance.commit).slice(0, 7)}`);
