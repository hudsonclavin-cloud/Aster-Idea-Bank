// Wraps idea 41's committed handoff as snapshots/signal-handoff.js (so the page opens on the chain's case with no
// network), then writes this module's sample handoff.json from it with the page's defaults.
//   node ideas/42-closing-in/build-sample.mjs        (then record the wrapper's provenance with tools/snapshot.mjs --sidecar-only)
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const HERE = path.dirname(new URL(import.meta.url).pathname);
const src = path.join(HERE, '..', '41-signal', 'handoff.json');
const h41 = JSON.parse(fs.readFileSync(src, 'utf8'));
fs.writeFileSync(path.join(HERE, 'snapshots', 'signal-handoff.js'),
  '/* Idea 41\'s committed sample handoff (ideas/41-signal/handoff.json), wrapped unmodified as a classic script (window.ClosingSignalSample) and require().\n * GENERATED by ideas/42-closing-in/build-sample.mjs; do not edit. */\n' +
  '(function (root) {\n  var D = ' + JSON.stringify(h41) + ';\n  if (typeof module === \'object\' && module.exports) module.exports = D;\n  else root.ClosingSignalSample = D;\n})(typeof self !== \'undefined\' ? self : this);\n');
delete require.cache[require.resolve('./load.cjs')];
const { K } = require('./load.cjs');
const src41 = K.importSignal(h41);
if (src41.refusal) { console.error(src41.refusal); process.exit(1); }
const R = K.run(src41, K.defaults());
if (R.refusal) { console.error(R.refusal); process.exit(1); }
const h = K.buildHandoff(R, '2026-10-31T12:00:00Z');
fs.writeFileSync(path.join(HERE, 'handoff.json'), JSON.stringify(h) + '\n');
console.log('wrote handoff.json:', (fs.statSync(path.join(HERE, 'handoff.json')).size / 1024).toFixed(1), 'KB; stand-off', h.outputs.standoff_state.value.utc, 'refusals', h.refusals.map((r) => (r.from ? r.from + ':' : '') + r.applies_to).join(', '));
