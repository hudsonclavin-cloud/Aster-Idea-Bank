#!/usr/bin/env node
// Writes snapshots/isa.js: PartForge's 1976 US Standard Atmosphere block (index.html lines 620-684 at 0974a62),
// copied VERBATIM out of idea 02's snapshot (ideas/02-hot-skin/snapshots/partforge.js, which idea 02's tests
// check against PartForge), between idea 02's own BEGIN/END markers, and wrapped so it loads as a classic script
// (window.PartForgeISA) and with require(). Only the atmosphere: idea 02's file also carries PartForge's material
// tables, which this module does not use. bell.test.mjs checks the block is byte-identical to idea 02's.
// Run from the bank root: node ideas/32-bell/build-data.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const here = path.dirname(fileURLToPath(import.meta.url));
const src = fs.readFileSync(path.join(here, '..', '02-hot-skin', 'snapshots', 'partforge.js'), 'utf8');
const BEGIN = '// ---- BEGIN verbatim index.html 620-684 @ 0974a62 ----', END = '// ---- END verbatim ----';
const a = src.indexOf(BEGIN), b = src.indexOf(END);
if (a < 0 || b < a) { console.error('markers not found in idea 02 snapshot'); process.exit(1); }
const block = src.slice(a, b + END.length);
const out = `/* GENERATED by ideas/32-bell/build-data.mjs from ideas/02-hot-skin/snapshots/partforge.js; do not edit.
 * PartForge's 1976 US Standard Atmosphere (index.html lines 620-684 at commit 0974a62), verbatim between the
 * markers. Classic script (window.PartForgeISA) and require(). */
(function (root, factory) {
  if (typeof module === 'object' && module.exports) module.exports = factory();
  else root.PartForgeISA = factory();
})(typeof self !== 'undefined' ? self : this, function () {
${block}
return { ISA_G0: ISA_G0, ISA_R: ISA_R, ISA_R0: ISA_R0, ISA_GAMMA: ISA_GAMMA, ISA_LAYERS: ISA_LAYERS, ISA_H_MAX: ISA_H_MAX, ISA_BASE_P: ISA_BASE_P, isa: isa };
});
`;
fs.writeFileSync(path.join(here, 'snapshots', 'isa.js'), out);
console.log('wrote snapshots/isa.js (' + out.length + ' bytes)');
