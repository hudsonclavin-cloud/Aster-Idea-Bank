#!/usr/bin/env node
// Builds this folder's snapshots. Nothing here is typed from memory: each number is copied by tools/snapshot.mjs or parsed
// out of a copied file, and each quoted sentence is found verbatim in what was fetched.
//   node ideas/50-the-long-way-round/build-data.mjs --aster        Aster's delta-v.ts, launch-vehicles.ts, bodies.ts and its
//                                                                  launch-vehicle golden test, copied, then parsed into snapshots/aster.js
//   node ideas/50-the-long-way-round/build-data.mjs --reuse        idea 49's 1976 atmosphere (PartForge isa.js) and idea 47's mass-ledger
//                                                                  functions, copied verbatim (the page's what-if runs them)
//   node ideas/50-the-long-way-round/build-data.mjs --nhats <dir>  JPL NHATS round trips (dir from oracle/fetch-sources.sh) into snapshots/nhats.js
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const BANK = path.resolve(HERE, '..', '..');
const ASTER = '/home/user/asteroid-mining-planner';
const SNAP = path.join(BANK, 'tools', 'snapshot.mjs');
const sha = (b) => crypto.createHash('sha256').update(b).digest('hex');
const snap = (repo, p, dest, note, extra = []) => execFileSync(process.execPath, [SNAP, repo, p, path.join(HERE, 'snapshots', dest), '--note', note, ...extra], { stdio: 'inherit' });
const wrap = (name, comment, D) => '/* ' + comment + '\n * GENERATED by ideas/50-the-long-way-round/build-data.mjs; do not edit. Classic script (window.' + name + ') and require(). */\n' +
  '(function (root) {\n  var D = ' + JSON.stringify(D) + ';\n  if (typeof module === \'object\' && module.exports) module.exports = D;\n  else root.' + name + ' = D;\n})(typeof self !== \'undefined\' ? self : this);\n';

// ------------------------------------------------------------------------------------------------ Aster
function aster() {
  snap(ASTER, 'src/v2/porkchop/delta-v.ts', 'aster-delta-v.ts.txt', 'Aster\'s injection delta-v from C3 (injectionDvFromC3), Earth GM and the 200 km parking radius, read as text');
  snap(ASTER, 'src/v2/porkchop/launch-vehicles.ts', 'aster-launch-vehicles.ts.txt', 'Aster\'s eight NASA LSP elvperf C3-to-payload curves and payloadAtC3 (interpolation between anchors only, BEYOND_CURVE outside), read as text');
  snap(ASTER, 'src/v2/core/constants/bodies.ts', 'aster-bodies.ts.txt', 'Aster\'s body radii; the Earth\'s (DE440, 6,378,136.6 m) is the one read');
  snap(ASTER, 'tests/v2-golden/launch-vehicles.golden.test.mjs', 'aster-launch-vehicles.golden.test.mjs.txt', 'Aster\'s golden pins on payloadAtC3 (nine exact values) that this folder\'s transcription must reproduce');
  const dv = fs.readFileSync(path.join(HERE, 'snapshots/aster-delta-v.ts.txt'), 'utf8');
  const lv = fs.readFileSync(path.join(HERE, 'snapshots/aster-launch-vehicles.ts.txt'), 'utf8');
  const bd = fs.readFileSync(path.join(HERE, 'snapshots/aster-bodies.ts.txt'), 'utf8');
  const gold = fs.readFileSync(path.join(HERE, 'snapshots/aster-launch-vehicles.golden.test.mjs.txt'), 'utf8');
  const num = (s) => Number(s.replace(/_/g, ''));
  const one = (src, re, what) => { const m = re.exec(src); if (!m) throw new Error('not found: ' + what); return m; };
  const lineOf = (src, idx) => src.slice(0, idx).split('\n').length;
  const mMu = one(dv, /export const EARTH_MU_KM3_PER_S2 = ([\d_.]+);/, 'EARTH_MU'), mLeo = one(dv, /export const LEO_PARKING_RADIUS_KM = ([\d_.]+);/, 'LEO');
  const mRe = one(bd, /earth:\s*\{ naifId: 399, radiusM:\s*([\d_.]+),/, 'earth radius');
  const mG0 = one(lv, /export const G0_MPS2 = ([\d.]+);/, 'G0');
  const mAsOf = one(lv, /const ELVPERF_AS_OF = '([^']+)';/, 'as-of'), mSrc = one(lv, /const ELVPERF_SOURCE = '([^']+)';/, 'source');
  // the vehicles: every { name, config, site, fairingM, ..., curve: [ { c3, payloadKg, basis } ] } block, in file order
  const vehicles = [];
  const blk = /\{\s*name: '([^']+)',\s*config: '([^']+)',\s*site: '([^']+)',\s*fairingM: ([\d.]+),\s*source: ELVPERF_SOURCE,\s*asOf: ELVPERF_AS_OF,\s*curve: \[([\s\S]*?)\],\s*\}/g;
  let b;
  while ((b = blk.exec(lv))) {
    const curve = [], an = /\{ c3: ([\d.]+), payloadKg: ([\d.]+), basis: '(official|estimated)' \}/g;
    let a; while ((a = an.exec(b[5]))) curve.push([+a[1], +a[2], a[3]]);
    vehicles.push({ name: b[1], config: b[2], site: b[3], fairing_m: +b[4], curve, line: lineOf(lv, b.index) });
  }
  const golden = [], gr = /\['([^']+)', '([^']+)', ([\d.]+), ([\d.]+)\]/g;
  let g; while ((g = gr.exec(gold))) golden.push([g[1], g[2], +g[3], +g[4]]);
  const anchorsCount = +one(gold, /assert\.equal\(anchors\.length, (\d+)\);/, 'anchor count')[1];
  const parsedAnchors = vehicles.reduce((n, v) => n + v.curve.length, 0);
  if (!vehicles.length || parsedAnchors !== anchorsCount) throw new Error('parsed ' + vehicles.length + ' vehicles and ' + parsedAnchors + ' anchors; Aster\'s golden test counts ' + anchorsCount);
  const D = {
    commit: execFileSync('git', ['rev-parse', 'HEAD'], { cwd: ASTER, encoding: 'utf8' }).trim(),
    earth_mu_km3_s2: num(mMu[1]), leo_parking_radius_km: num(mLeo[1]), earth_radius_m: num(mRe[1]), g0_m_s2: +mG0[1],
    cite: { earth_mu: 'src/v2/porkchop/delta-v.ts:' + lineOf(dv, mMu.index), leo: 'src/v2/porkchop/delta-v.ts:' + lineOf(dv, mLeo.index),
      earth_radius: 'src/v2/core/constants/bodies.ts:' + lineOf(bd, mRe.index), g0: 'src/v2/porkchop/launch-vehicles.ts:' + lineOf(lv, mG0.index) },
    elvperf: { source: mSrc[1], as_of: mAsOf[1], file: 'src/v2/porkchop/launch-vehicles.ts', vehicles },
    golden: { file: 'tests/v2-golden/launch-vehicles.golden.test.mjs', payload: golden, anchors: anchorsCount },
  };
  const out = path.join(HERE, 'snapshots/aster.js');
  fs.writeFileSync(out, wrap('LWR_ASTER', 'Aster constants and launch-vehicle curves parsed out of the four copied .txt files beside this one (Aster @ ' + D.commit.slice(0, 7) + ').', D));
  execFileSync(process.execPath, [SNAP, ASTER, 'src/v2/porkchop/launch-vehicles.ts', out, '--sidecar-only', '--note',
    'derived by build-data.mjs --aster: parsed (not retyped) from snapshots/aster-delta-v.ts.txt (EARTH_MU_KM3_PER_S2, LEO_PARKING_RADIUS_KM), aster-launch-vehicles.ts.txt (G0_MPS2, ELVPERF_SOURCE/AS_OF, the eight vehicles and their 38 anchors, the count checked against the golden test), aster-bodies.ts.txt (earth radiusM) and the golden test (nine payloadAtC3 pins)'], { stdio: 'inherit' });
  console.log('aster.js:', vehicles.length, 'vehicles,', vehicles.reduce((n, v) => n + v.curve.length, 0), 'anchors,', golden.length, 'golden pins');
}

// ------------------------------------------------------------------------------------------------ reuse, verbatim
function reuse() {
  snap(BANK, 'ideas/49-hot-return/snapshots/isa.js', 'isa.js', 'PartForge\'s 1976 atmosphere isa() as ideas 48 and 49 carry it, byte-identical: the air density at the ground for the main parachute in the what-if');
  // idea 47's mass ledger, the functions the what-if calls, excerpted verbatim (the test checks each block is a byte-for-byte substring)
  const src = fs.readFileSync(path.join(BANK, 'ideas/47-way-home/home.js'), 'utf8').split('\n');
  const from = src.findIndex((l) => l.startsWith('    function burnable(B, f, o)')), to = src.findIndex((l) => l.startsWith('    function capacity(B, waitS)'));
  if (from < 0 || to < 0) throw new Error('idea 47 ledger functions not found');
  let end = to; while (src[end] !== '    }') end++;
  const block = src.slice(from, end + 1).join('\n');
  if (!/function ledger\(B, waitS, tofS, burns, m\)/.test(block) || !/function materialMax\(B, waitS, tofS, burns\)/.test(block)) throw new Error('excerpt incomplete');
  const body = '/* Idea 47\'s return mass ledger, excerpted verbatim from ideas/47-way-home/home.js (lines ' + (from + 1) + '-' + (end + 1) + ': burnable, burn, tcmOf, burnsOf,\n' +
    ' * ledger, materialMax, capacity) by ideas/50-the-long-way-round/build-data.mjs --reuse; do not edit. tcmOf and burnsOf are carried but not called\n' +
    ' * (they need idea 47\'s Lucy execution model); the what-if calls ledger(), materialMax() and capacity() with idea 47\'s own burns.\n' +
    ' * Classic script (window.LWR_HOME_LEDGER) and require(). */\n' +
    '(function (root, factory) {\n  if (typeof module === \'object\' && module.exports) module.exports = factory();\n  else root.LWR_HOME_LEDGER = factory();\n})(typeof self !== \'undefined\' ? self : this, function () {\n  \'use strict\';\n' +
    '  var DAY = 86400, EXEC = null, vinfMax = null;\n  function num(x) { return typeof x === \'number\' && isFinite(x); }\n' +
    '  // ---- home.js lines ' + (from + 1) + '-' + (end + 1) + '\n' + block + '\n  return { ledger: ledger, materialMax: materialMax, capacity: capacity, burnable: burnable };\n});\n';
  const out = path.join(HERE, 'snapshots/home-ledger.js');
  fs.writeFileSync(out, body);
  execFileSync(process.execPath, [SNAP, BANK, 'ideas/47-way-home/home.js', out, '--sidecar-only', '--note',
    'derived by build-data.mjs --reuse: lines ' + (from + 1) + '-' + (end + 1) + ' of idea 47\'s home.js (burnable, burn, tcmOf, burnsOf, ledger, materialMax, capacity) copied verbatim inside a wrapper that supplies DAY = 86400 and num(); mission.test.mjs checks the block is a byte-for-byte substring of home.js'], { stdio: 'inherit' });
  console.log('home-ledger.js: home.js lines', from + 1, 'to', end + 1);
}

// ------------------------------------------------------------------------------------------------ NHATS
function strip(html) {
  return html.replace(/<script[\s\S]*?<\/script>/g, '').replace(/<style[\s\S]*?<\/style>/g, '').replace(/<[^>]+>/g, ' ')
    .replace(/&nbsp;/g, ' ').replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&#8217;|&rsquo;/g, '’').replace(/\s+/g, ' ');
}
function nhats(dir) {
  if (!dir || !fs.existsSync(path.join(dir, 'nhats'))) { console.error('usage: build-data.mjs --nhats <dir from oracle/fetch-sources.sh>'); process.exit(2); }
  const files = fs.readdirSync(path.join(dir, 'nhats')).filter((f) => f.endsWith('.json')).sort();
  const cav = fs.readFileSync(path.join(dir, 'cneos-caveats.html'), 'utf8'), doc = fs.readFileSync(path.join(dir, 'ssd-api-nhats.html'), 'utf8');
  const cavT = strip(cav), docT = strip(doc);
  // the sentence that defines the total; NHATS's own markup splits "C 3" and "km 2 /sec 2" (sub- and superscripts)
  const QUOTES = {
    total: [cavT, 'The total delta-V includes the Earth departure maneuver from a 400 km altitude circular parking orbit, the maneuver to match the NEA\'s velocity at arrival, the maneuver to depart the NEA and, if necessary, a maneuver to control the atmospheric re-entry speed during Earth return.'],
    entry: [cavT, 'Earth atmospheric entry speed less than or equal to 12 km/s at an altitude of 125 km'],
    c3: [docT, 'nhats_traj.c3 C3 (km2/s2)'],
    dv_dep_park: [docT, 'nhats_traj.dv_dep_park Earth Departure dV (km/s)'],
    vrel_arr_neo: [docT, 'nhats_traj.vrel_arr_neo dV to Arrive at NEA (km/s)'],
    vrel_dep_neo: [docT, 'nhats_traj.vrel_dep_neo dV to Depart NEA (km/s)'],
    vrel_arr_earth: [docT, 'nhats_traj.vrel_arr_earth Earth return dV (km/s)'],
    method: [strip(fs.readFileSync(path.join(dir, 'cneos-caveats.html'), 'utf8')), 'patched conics with Lambert solutions'],
  };
  const quotes = {};
  for (const k of Object.keys(QUOTES)) {
    const [t, q] = QUOTES[k], qq = q.replace(/’/g, '\'');
    const tt = t.replace(/’/g, '\'');
    if (!tt.includes(qq)) throw new Error('quote not found verbatim: ' + k);
    quotes[k] = q;
  }
  const leo = +/from a (\d+) km altitude circular parking orbit/.exec(quotes.total)[1];
  const cols = ['des', 'tid', 'kind', 'launch', 'dur_out', 'dur_at', 'dur_ret', 'dur_total', 'c3', 'v_dep_earth', 'dv_dep_park', 'vrel_arr_neo', 'vrel_dep_neo', 'vrel_arr_earth', 'v_arr_earth', 'dec_arr', 'dv_total', 'query'];
  const rows = [], seen = new Set(), shas = [];
  for (const f of files) {
    const raw = fs.readFileSync(path.join(dir, 'nhats', f)), J = JSON.parse(raw);
    shas.push(sha(raw));
    for (const kind of ['min_dv_traj', 'min_dur_traj']) {
      const t = J[kind]; if (!t || seen.has(t.tid)) continue;
      seen.add(t.tid);
      rows.push([J.des, +t.tid, kind === 'min_dv_traj' ? 'least_dv' : 'shortest', t.launch, +t.dur_out, +t.dur_at, +t.dur_ret, +t.dur_total, +t.c3, +t.v_dep_earth, +t.dv_dep_park,
        +t.vrel_arr_neo, +t.vrel_dep_neo, +t.vrel_arr_earth, +t.v_arr_earth, +t.dec_arr, +t.dv_total, f.replace(/\.json$/, '')]);
    }
  }
  rows.sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : a[1] - b[1]));
  const D = { retrieved: new Date().toISOString().slice(0, 10), api: 'https://ssd-api.jpl.nasa.gov/nhats.api', caveats: 'https://cneos.jpl.nasa.gov/nhats/caveats.html',
    doc: 'https://ssd-api.jpl.nasa.gov/doc/nhats.html', parking_altitude_km: leo, quotes, columns: cols, rows,
    note: 'Each query (des, dv, dur, stay, launch; the file name) returns NHATS\'s least-delta-v and shortest round trips; both are kept, once per trajectory id. Units as NHATS gives them: km/s, km^2/s^2, days, degrees.' };
  const out = path.join(HERE, 'snapshots/nhats.js');
  const body = wrap('LWR_NHATS', 'JPL NHATS round trips (the 43 queries behind idea 47\'s NHATS rows), every term of each, and the sentences that define them.', D);
  fs.writeFileSync(out, body);
  const rollup = sha(shas.join('\n'));
  fs.writeFileSync(out + '.provenance.json', JSON.stringify({
    repo: D.api, path: 'nhats.api?des=<des>&dv=<dv>&dur=<dur>&stay=<stay>&launch=<launch> for the 43 queries in rows[*].query; ' + D.caveats + '; ' + D.doc,
    commit: 'retrieved ' + D.retrieved, retrieved: D.retrieved, sourceSha256: rollup, sha256Rule: 'sha256 of the newline-joined per-file sha256 values of the 43 NHATS responses, files in name order',
    caveatsSha256: sha(cav), docSha256: sha(doc), writtenSha256: sha(body),
    license: 'NASA/JPL (CNEOS, SSD API) public data; US Government work, no copyright asserted in the United States',
    note: 'derived by build-data.mjs --nhats from the directory oracle/fetch-sources.sh writes: min_dv_traj and min_dur_traj of each response, once per tid (' + rows.length + ' trajectories), and seven quoted sentences found verbatim (after tags are stripped)',
  }, null, 1) + '\n');
  console.log('nhats.js:', rows.length, 'trajectories from', files.length, 'responses; parking orbit', leo, 'km');
}

const a = process.argv[2];
if (a === '--aster') aster();
else if (a === '--reuse') reuse();
else if (a === '--nhats') nhats(process.argv[3]);
else { console.error('usage: build-data.mjs --aster | --reuse | --nhats <dir>'); process.exit(2); }
