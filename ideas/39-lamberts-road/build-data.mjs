// Cells are drawn with a seeded LCG; quotas by arrival before / after an MJD split (Apophis: its 2029-04-13 encounter).
function mdesign(file, seed, quotas, splitMjd) {
  const buf = fs.readFileSync(path.join(fetched, file)), d = JSON.parse(buf);
  let s = seed >>> 0; const rnd = () => ((s = (s * 1664525 + 1013904223) >>> 0) / 4294967296);
  const cells = [], got = [0, 0];
  while (got[0] < quotas[0] || got[1] < quotas[1]) {
    const i = Math.floor(rnd() * d.dep_date.length), j = Math.floor(rnd() * d.tof.length), side = d.dep_date[i] + d.tof[j] < splitMjd ? 0 : 1;
    if (got[side] >= quotas[side]) continue;
    got[side]++;
    cells.push([d.dep_date[i], d.tof[j], d.vinf_dep[j][i], d.vinf_arr[j][i], d.decl_dep[j][i]]);
  }
  return { sha256: sha256(buf), out: { object: d.object, signature: d.signature, constraints: d.md_constraints, modified: d.modified, fields: d.fields, selectedMissions: d.selectedMissions,
    sampleFields: ['MJD0', 'tof_d', 'vinf_dep_km_s', 'vinf_arr_km_s', 'decl_dep_deg'], sample: cells } };
}
