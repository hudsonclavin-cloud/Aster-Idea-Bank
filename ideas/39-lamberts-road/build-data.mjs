function writeData(file, globalName, header, data) {
  const body = `/* ${header}\n * GENERATED by ideas/39-lamberts-road/build-data.mjs; do not edit. Classic script (window.${globalName}) and require(). */\n` +
    `(function (root) {\n  var D = ${JSON.stringify(data)};\n  if (typeof module === 'object' && module.exports) module.exports = D;\n  else root.${globalName} = D;\n})(typeof self !== 'undefined' ? self : this);\n`;
  fs.writeFileSync(snap(file), body);
  console.log('wrote', file, body.length, 'bytes');
}
