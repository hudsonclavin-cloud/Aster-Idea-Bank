#!/usr/bin/env node
// Derives this idea's data from the Aster checkout, in order (run from the bank root):
//
//   1. node tools/snapshot.mjs /home/user/asteroid-mining-planner tests/fixtures/v2/lambert-screen-cache.json \
//        ideas/10-edge-of-the-grid/snapshots/metadata.json --pick metadata --note "…"
//      (a true excerpt: the cache's metadata object, the only thing the lattice is derived from)
//   2. node ideas/10-edge-of-the-grid/edge-census.mjs --json ideas/10-edge-of-the-grid/snapshots/edge-census.json \
//        > ideas/10-edge-of-the-grid/example.txt
//   3. node tools/snapshot.mjs /home/user/asteroid-mining-planner tests/fixtures/v2/lambert-screen-cache.json \
//        ideas/10-edge-of-the-grid/snapshots/edge-census.json --sidecar-only --note "derived by edge-census.mjs: …"
//   4. node ideas/10-edge-of-the-grid/build-data.mjs        (this script: wraps 1 and 2 as a classic script)
//   5. node tools/snapshot.mjs /home/user/asteroid-mining-planner tests/fixtures/v2/lambert-screen-cache.json \
//        ideas/10-edge-of-the-grid/snapshots/edge-census.data.js --sidecar-only --note "derived by build-data.mjs: …"
//
// index.html cannot fetch() a sibling JSON file from file://, so this wraps snapshots/metadata.json,
// snapshots/edge-census.json and their provenance sidecars as window.EDGE_CENSUS (module.exports under
// Node), serialised on one line to keep the folder small (snapshots/edge-census.json is the readable
// copy). Nothing is retyped: the JSON bytes are parsed and re-serialised; a test checks deep equality.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const snap = (name) => path.join(here, 'snapshots', name);
const read = (name) => JSON.parse(fs.readFileSync(snap(name), 'utf8'));

const metadata = read('metadata.json');
const metadataProvenance = read('metadata.json.provenance.json');
const census = read('edge-census.json');
const censusProvenance = read('edge-census.json.provenance.json');

const body = { metadata: metadata.metadata, metadataProvenance, census, censusProvenance };
const out = `// Generated by build-data.mjs from snapshots/metadata.json and snapshots/edge-census.json and their
// provenance sidecars. Do not edit. Aster ${censusProvenance.path} @ ${censusProvenance.commit}
// (cache sha256 ${censusProvenance.sourceSha256}).
(function (root, factory) {
  if (typeof module === 'object' && module.exports) module.exports = factory();
  else root.EDGE_CENSUS = factory();
})(typeof self !== 'undefined' ? self : this, function () {
  return ${JSON.stringify(body)};
});
`;
fs.writeFileSync(snap('edge-census.data.js'), out);
console.log(`wrote ${path.relative(process.cwd(), snap('edge-census.data.js'))} (${out.length} bytes) from ${censusProvenance.path} @ ${String(censusProvenance.commit).slice(0, 7)}`);
