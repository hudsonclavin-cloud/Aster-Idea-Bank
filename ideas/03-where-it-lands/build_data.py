#!/usr/bin/env python3
"""
build_data.py -- derive the three data modules under snapshots/ from a Skyhook checkout.

Standard library only. Run from anywhere:

    python3 ideas/03-where-it-lands/build_data.py [--skyhook /home/user/skyhook]

Writes (each as a classic-script/CommonJS module so index.html works from file://
and Node tests can require() it):

  snapshots/decision_grid.js   finance/decision_grid.json embedded VERBATIM (the file's
                               exact text between /*<json>*/ and /*</json>*/ markers),
                               plus a non-enumerable __source record (path, commit, sha256).
  snapshots/rev_a.excerpt.js   params/rev_a.json, keys _meta, economics, kinematics,
                               mass_ratio, materials, market_thresholds (values unchanged,
                               re-serialised with indent=1).
  snapshots/ladder.js          the workbook's Assumptions sheet rows 2-16, columns A-E
                               (tools/financial/skyhook_financial_model.xlsx), parsed from
                               the xlsx zip with zipfile + xml.etree. The three ladder
                               columns are read from row 2; keys for the rows this idea
                               uses mirror finance/skyhook_finance.py _LADDER_ROWS.

After running, record provenance with the bank's tool (one sidecar per file):
  node tools/snapshot.mjs <skyhook> finance/decision_grid.json <here>/snapshots/decision_grid.js --sidecar-only --note "..."
  node tools/snapshot.mjs <skyhook> params/rev_a.json <here>/snapshots/rev_a.excerpt.js --sidecar-only --note "..."
  node tools/snapshot.mjs <skyhook> tools/financial/skyhook_financial_model.xlsx <here>/snapshots/ladder.js --sidecar-only --note "..."
"""
import argparse
import hashlib
import json
import re
import subprocess
import sys
import zipfile
import xml.etree.ElementTree as ET
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "snapshots"

GRID_PATH = "finance/decision_grid.json"
REV_A_PATH = "params/rev_a.json"
WORKBOOK_PATH = "tools/financial/skyhook_financial_model.xlsx"
REV_A_KEYS = ["_meta", "economics", "kinematics", "mass_ratio", "materials", "market_thresholds"]

# Row keys this idea reads, mirroring finance/skyhook_finance.py _LADDER_ROWS (lines 56-71
# at 34935cb). Only the rows the page uses are named; every row is still carried verbatim.
LADDER_KEYS = {
    "strength_retention": 3,
    "construction_launch_per_kg": 5,
    "ops_wear_per_kg": 8,
    "customer_price_per_kg": 10,
    "tip_speed_kms": 15,
}

NS = {"m": "http://schemas.openxmlformats.org/spreadsheetml/2006/main",
      "r": "http://schemas.openxmlformats.org/officeDocument/2006/relationships",
      "rel": "http://schemas.openxmlformats.org/package/2006/relationships"}


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def git(repo: Path, *args: str) -> str:
    return subprocess.run(["git", *args], cwd=repo, capture_output=True, text=True,
                          check=True).stdout.strip()


def module(global_name: str, body_js: str, header: str) -> str:
    """Wrap a JS expression body in the Idea Bank UMD shape."""
    return (
        f"// {header}\n"
        "// Generated by build_data.py; do not edit by hand.\n"
        "(function (root, factory) {\n"
        "  if (typeof module === 'object' && module.exports) module.exports = factory();\n"
        f"  else root.{global_name} = factory();\n"
        "})(typeof self !== 'undefined' ? self : this, function () {\n"
        f"{body_js}"
        "});\n"
    )


def source_record(repo: Path, rel: str, data: bytes, mode: str, note: str) -> dict:
    return {
        "path": rel,
        "commit": git(repo, "rev-parse", "HEAD"),
        "pathLastChanged": git(repo, "log", "-1", "--format=%h %cI", "--", rel),
        "sourceSha256": sha256(data),
        "sourceBytes": len(data),
        "mode": mode,
        "note": note,
    }


def build_grid(repo: Path) -> Path:
    src = repo / GRID_PATH
    data = src.read_bytes()
    text = data.decode("utf-8")
    json.loads(text)  # must parse; we embed the text itself
    if "/*</json>*/" in text or "*/" in text:
        sys.exit("grid text contains a comment terminator; cannot embed verbatim")
    rec = source_record(repo, GRID_PATH, data, "verbatim-embed",
                        "the JSON text between the /*<json>*/ and /*</json>*/ markers is the "
                        "source file byte for byte; sha256 of that text equals sourceSha256")
    body = (
        "  var grid = /*<json>*/" + text + "/*</json>*/;\n"
        "  Object.defineProperty(grid, '__source', { value: " + json.dumps(rec, indent=2)
        .replace("\n", "\n  ") + ", enumerable: false });\n"
        "  return grid;\n"
    )
    out = OUT / "decision_grid.js"
    out.write_text(module("DECISION_GRID", body,
                          f"Skyhook {GRID_PATH} @ {rec['commit'][:7]}, embedded verbatim."),
                   encoding="utf-8")
    return out


def build_rev_a(repo: Path) -> Path:
    src = repo / REV_A_PATH
    data = src.read_bytes()
    full = json.loads(data.decode("utf-8"))
    picked = {k: full[k] for k in REV_A_KEYS}
    rec = source_record(repo, REV_A_PATH, data, "excerpt",
                        f"keys {', '.join(REV_A_KEYS)} of the file, values unchanged, "
                        "re-serialised with indent=1")
    rec["picked"] = REV_A_KEYS
    body = (
        "  var revA = " + json.dumps(picked, indent=1, ensure_ascii=False).replace("\n", "\n  ") + ";\n"
        "  Object.defineProperty(revA, '__source', { value: " + json.dumps(rec, indent=2)
        .replace("\n", "\n  ") + ", enumerable: false });\n"
        "  return revA;\n"
    )
    out = OUT / "rev_a.excerpt.js"
    out.write_text(module("REV_A", body,
                          f"Skyhook {REV_A_PATH} @ {rec['commit'][:7]}, excerpt."),
                   encoding="utf-8")
    return out


def cell_value(c):
    """Value of a <c> element: inline string, shared string index (unsupported here), or number."""
    t = c.get("t")
    if t == "inlineStr":
        return "".join(x.text or "" for x in c.iter(f"{{{NS['m']}}}t"))
    v = c.find("m:v", NS)
    if v is None or v.text is None:
        return None
    if t == "s":
        raise SystemExit("shared strings are not used by this workbook; parser does not handle them")
    if t == "str" or t == "b":
        return v.text
    f = float(v.text)
    return int(f) if f.is_integer() else f


def build_ladder(repo: Path) -> Path:
    src = repo / WORKBOOK_PATH
    data = src.read_bytes()
    with zipfile.ZipFile(src) as z:
        wb = ET.fromstring(z.read("xl/workbook.xml"))
        rid = None
        for sh in wb.iter(f"{{{NS['m']}}}sheet"):
            if sh.get("name") == "Assumptions":
                rid = sh.get(f"{{{NS['r']}}}id")
        if rid is None:
            sys.exit("no sheet named Assumptions")
        rels = ET.fromstring(z.read("xl/_rels/workbook.xml.rels"))
        target = None
        for rel in rels.iter(f"{{{NS['rel']}}}Relationship"):
            if rel.get("Id") == rid:
                target = rel.get("Target")
        if target is None:
            sys.exit(f"no relationship {rid}")
        target = target.lstrip("/")
        if not target.startswith("xl/"):
            target = "xl/" + target
        sheet = ET.fromstring(z.read(target))
    cells = {}
    for c in sheet.iter(f"{{{NS['m']}}}c"):
        cells[c.get("r")] = cell_value(c)
    header = [cells.get(f"{col}2") for col in "BCD"]
    rows = []
    for r in range(3, 17):
        rows.append({
            "row": r,
            "parameter": cells.get(f"A{r}"),
            header[0]: cells.get(f"B{r}"),
            header[1]: cells.get(f"C{r}"),
            header[2]: cells.get(f"D{r}"),
            "note": cells.get(f"E{r}"),
        })
    ladder = {
        "sheet": "Assumptions",
        "range": "A2:E16",
        "title": cells.get("A1"),
        "columns": header,
        "keys": LADDER_KEYS,
        "keys_note": ("row numbers mirror finance/skyhook_finance.py _LADDER_ROWS; "
                      "each key names the workbook row whose value the page reads"),
        "rows": rows,
    }
    rec = source_record(repo, WORKBOOK_PATH, data, "derived",
                        "Assumptions sheet A2:E16 parsed from the xlsx zip (zipfile + "
                        "xml.etree; inline strings and plain numbers only, no formulas)")
    body = (
        "  var ladder = " + json.dumps(ladder, indent=1, ensure_ascii=False).replace("\n", "\n  ") + ";\n"
        "  Object.defineProperty(ladder, '__source', { value: " + json.dumps(rec, indent=2)
        .replace("\n", "\n  ") + ", enumerable: false });\n"
        "  return ladder;\n"
    )
    out = OUT / "ladder.js"
    out.write_text(module("LADDER", body,
                          f"Skyhook {WORKBOOK_PATH} @ {rec['commit'][:7]}, Assumptions sheet A2:E16."),
                   encoding="utf-8")
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--skyhook", default="/home/user/skyhook", help="path to the Skyhook checkout")
    a = ap.parse_args()
    repo = Path(a.skyhook).resolve()
    if not (repo / ".git").exists():
        print(f"not a git checkout: {repo}", file=sys.stderr)
        return 2
    OUT.mkdir(parents=True, exist_ok=True)
    for f in (build_grid(repo), build_rev_a(repo), build_ladder(repo)):
        print(f"wrote {f.relative_to(HERE)}  ({f.stat().st_size} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
