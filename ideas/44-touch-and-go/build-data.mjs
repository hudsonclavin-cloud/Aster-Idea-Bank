// Builds this module's derived data from the primary sources (oracle/fetch-sources.sh) and the bank's committed ideas.
//   bash ideas/44-touch-and-go/oracle/fetch-sources.sh /tmp/src44
//   node ideas/44-touch-and-go/build-data.mjs /tmp/src44            (snapshots/tag-recon.js, lumpy-handoff.js, sidecars)
//   node ideas/44-touch-and-go/build-data.mjs --sample               (handoff.json from the kernel, after the snapshots exist)
// What it does:
//  1. checks every quoted figure in snapshots/tag-sources.js is in its document (whitespace normalised), and records
//     each document's sha256 in snapshots/tag-sources.js.provenance.json;
//  2. excerpts JPL Horizons' OSIRIS-REx descent (ORX_merged, -64 about Bennu, ICRF, TDB) into snapshots/tag-recon.js:
//     every 600 s on the 4-h leg, every 20 s after Checkpoint, the rows bracketing each burn, and the last row of the
//     descent segment (21:51:02.0 TDB, taken as contact); with idea 42's own sunlight and solar tide (closing.js accel()
//     with Bennu's pull off, OSIRIS-APEX area per mass) evaluated at each row, as idea 43 did for Orbital B;
//  3. wraps idea 43's committed handoff.json, unmodified, as snapshots/lumpy-handoff.js (the page opens on it).
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const HERE = path.dirname(new URL(import.meta.url).pathname);
const BANK = path.join(HERE, '..', '..');
const sha = (b) => crypto.createHash('sha256').update(b).digest('hex');
const wrap = (name, comment, D) => '/* ' + comment + '\n * GENERATED by ideas/44-touch-and-go/build-data.mjs; do not edit. Classic script (window.' + name + ') and require(). */\n' +
  '(function (root) {\n  var D = ' + JSON.stringify(D) + ';\n  if (typeof module === \'object\' && module.exports) module.exports = D;\n  else root.' + name + ' = D;\n})(typeof self !== \'undefined\' ? self : this);\n';

if (process.argv.includes('--sample')) {
  const { K, sample43 } = require('./load.cjs');
  const src = K.importLumpy(sample43());
  if (src.refusal) { console.error(src.refusal); process.exit(1); }
  const R = K.run(src, K.defaults());
  if (R.refusal) { console.error(R.refusal); process.exit(1); }
  const h = K.buildHandoff(R, '2026-10-31T12:00:00Z');
  fs.writeFileSync(path.join(HERE, 'handoff.json'), JSON.stringify(h) + '\n');
  console.log('wrote handoff.json', (fs.statSync(path.join(HERE, 'handoff.json')).size / 1024).toFixed(1), 'KB; refusals', h.refusals.map((r) => (r.from ? r.from + ':' : '') + r.applies_to).join(', '));
  process.exit(0);
}

const DIR = process.argv[2];
if (!DIR || !fs.existsSync(DIR)) { console.error('usage: node build-data.mjs <directory written by oracle/fetch-sources.sh> | --sample'); process.exit(2); }
const rd = (f) => fs.readFileSync(path.join(DIR, f));
const norm = (s) => s.replace(/[\u2018\u2019]/g, '\'').replace(/\s+/g, ' ');   // straight and curly apostrophes compare equal
const htmlText = (b) => norm(b.toString('utf8').replace(/<script[\s\S]*?<\/script>|<style[\s\S]*?<\/style>/g, ' ').replace(/<[^>]+>/g, ' ')
  .replace(/&#8217;|&rsquo;/g, '’').replace(/&#8211;|&ndash;/g, '–').replace(/&amp;/g, '&').replace(/&nbsp;|&#160;/g, ' ').replace(/&#039;|&#39;/g, '\''));
const FILES = {
  berry2021: 'berry2021-tag-performance', berry2020: 'berry2020-revisiting-tag', may2014: 'may2014-tag-mission-design', walsh2022: 'walsh2022-sampleability', posttag: 'post-tag-trajectory',
  nasa20201021: 'nasa-2020-10-21-tag.html', nasa20210415: 'nasa-2021-04-15-mark.html', nasa20220707: 'nasa-2022-07-07-ballpit.html', nasa20240215: 'nasa-2024-02-15-mass.html', horizons: 'horizons-orex-tag-10s.txt'
};
const docText = {}, docSha = {};
for (const [k, f] of Object.entries(FILES)) {
  if (f.endsWith('.html')) { docText[k] = htmlText(rd(f)); docSha[f] = sha(rd(f)); }
  else if (f.endsWith('.txt')) { docText[k] = norm(rd(f).toString('utf8')); docSha[f] = sha(rd(f)); }
  else { docText[k] = norm(rd(f + '.txt').toString('utf8')) + ' | ' + norm(rd(f + '.raw.txt').toString('utf8')); docSha[f + '.pdf'] = sha(rd(f + '.pdf')); }
}
// 1. every quote in tag-sources.js is in its document
const S = require('./snapshots/tag-sources.js');
let quotes = 0;
(function walk(o, where) {
  if (!o || typeof o !== 'object') return;
  if (o.q && o.doc) {
    (Array.isArray(o.q) ? o.q : [o.q]).forEach((q) => {
      if (!docText[o.doc].includes(norm(q))) { console.error('quote not found in ' + o.doc + ' (' + where + '): ' + q); process.exit(1); }
      quotes++;
    });
  }
  for (const k of Object.keys(o)) if (k !== 'q') walk(o[k], where + '.' + k);
})(S, 'S');

// the execution-error arrays are the printed rows
{
  const E = S.execution, f = (x) => (Number.isInteger(x) && x >= 10 ? String(x) : x.toFixed(1));
  Object.keys(E.rows).forEach((k, i) => {
    const p = E.prelaunch[k], l = E.late[k];
    const row = E.rows[k] + ' RSS(' + f(p[0]) + 'mm/s, ' + f(p[1]) + '%ΔV) ' + f(p[2]) + 'mm/s+' + f(p[3]) + '%ΔV RSS(' + f(l[0]) + 'mm/s, ' + f(l[1]) + '%ΔV) ' + f(l[2]) + 'mm/s+' + f(l[3]) + '%ΔV';
    if (row !== E.q[i]) { console.error('execution row ' + k + ' does not re-form: ' + row + ' vs ' + E.q[i]); process.exit(1); }
  });
}
// 2. the reconstruction excerpt
const rows = (f) => rd(f).toString('utf8').split('$$SOE')[1].split('$$EOE')[0].trim().split('\n').map((l) => {
  const p = l.split(',').map((s) => s.trim()); return { jd: +p[0], cal: p[1].slice(17), s: p.slice(2, 8).map((x) => +x * 1000) };
});
const R10 = rows('horizons-orex-tag-10s.txt'), R05 = rows('horizons-orex-tag-contact-0.5s.txt'), BH = rows('horizons-bennu-helio-tag.txt');
const tdb = (jd) => (jd - 2451545.0) * 86400;
const pick = (hms) => { const r = R10.find((q) => q.cal === hms + '.0000'); if (!r) throw new Error('no row ' + hms); return r; };
const keep = new Map();
const add = (r) => keep.set(r.cal, r);
const sec = (hms) => { const [h, m, s] = hms.split(':').map(Number); return h * 3600 + m * 60 + s; };
const hmsOf = (x) => [Math.floor(x / 3600), Math.floor(x / 60) % 60, x % 60].map((v) => String(v).padStart(2, '0')).join(':');
for (let x = sec('17:31:00'); x <= sec('21:21:00'); x += 600) add(pick(hmsOf(x)));
['17:30:30', '21:29:20', '21:40:30'].forEach((h) => add(pick(h)));
for (let x = sec('21:31:00'); x <= sec('21:40:20'); x += 20) add(pick(hmsOf(x)));
for (let x = sec('21:41:00'); x <= sec('21:51:00'); x += 20) add(pick(hmsOf(x)));
const last = R05.find((q) => q.cal === '21:51:02.0000'), after = R05.find((q) => q.cal === '21:51:02.5000');
// the descent segment ends between these two: the range jumps by ~1.9 m as Horizons switches to the pre-TAG prediction
if (Math.abs(Math.hypot(...after.s.slice(0, 3)) - Math.hypot(...last.s.slice(0, 3))) < 1) { console.error('no segment jump at 21:51:02-02.5'); process.exit(1); }
add(last);
const kept = [...keep.values()].sort((a, b) => a.jd - b.jd);
const K42 = require(path.join(BANK, 'ideas/42-closing-in/load.cjs')).K;
const SRC = require('./snapshots/approach-sources.js');
const am = 1 / SRC.aas24063.massToArea_kg_m2, b0 = BH[0], ctx = K42.bennuCtx(b0.s, tdb(b0.jd), am, 0);
const r12 = (x) => +x.toPrecision(12);
const geo = rd('horizons-orex-geo-tag.txt').toString('utf8').split('$$SOE')[1].split('$$EOE')[0].trim().split('\n').map((l) => l.trim().split(/\s+/));
const lt = geo.find((p) => p[1] === '21:50:00.000');
const D = {
  note: 'JPL Horizons, OSIRIS-REx (-64) relative to Bennu (@2101955), ICRF, TDB, source ORX_merged (descent segment ' + S.reconstruction.segment_descent + '); m and m/s. sun: idea 42 closing.js accel(t, rho, bennuCtx(Bennu Horizons row 2020-10-20 17:00 TDB, t0, 1/81.119, mu = 0)), m/s^2.',
  t: kept.map((r) => r12(tdb(r.jd))), utcNote: 'UTC = TDB - 69.184 s',
  s: kept.map((r) => r.s.map((x, i) => (i < 3 ? +x.toFixed(6) : +x.toFixed(9)))),
  sun: kept.map((r) => K42.accel(tdb(r.jd), r.s.slice(0, 3), ctx).map(r12)),
  burns: { ODM: { pre: tdb(pick('17:30:30').jd), post: tdb(pick('17:31:00').jd) }, CP: { pre: tdb(pick('21:29:20').jd), post: tdb(pick('21:31:00').jd) }, MP: { pre: tdb(pick('21:40:30').jd), post: tdb(pick('21:41:00').jd) } },
  contact: { t: tdb(last.jd), next_t: tdb(after.jd), jump_m: +(Math.hypot(...after.s.slice(0, 3)) - Math.hypot(...last.s.slice(0, 3))).toFixed(4), note: 'last sample of the descent segment (0.5 s steps); the next belongs to the pre-TAG prediction od292' },
  bennuHelio: { t: tdb(b0.jd), s: b0.s },
  lightTime_min_at_2150utc: +lt[4],   // columns: date, time, delta (au), deldot (km/s), one-way light time (min)
  area_per_mass_m2_kg: am
};
fs.writeFileSync(path.join(HERE, 'snapshots', 'tag-recon.js'), wrap('TouchRecon', 'OSIRIS-REx\'s Touch-and-Go descent at Bennu, 2020-10-20, excerpted from JPL Horizons, with idea 42\'s sunlight along it.', D));

// 3. idea 43's handoff, wrapped unmodified
const h43 = JSON.parse(fs.readFileSync(path.join(BANK, 'ideas/43-lumpy/handoff.json'), 'utf8'));
fs.writeFileSync(path.join(HERE, 'snapshots', 'lumpy-handoff.js'), wrap('TouchLumpySample', 'Idea 43\'s committed sample handoff (ideas/43-lumpy/handoff.json), unmodified.', h43));

// sidecars for the two hand-made files (lumpy-handoff.js's is written by tools/snapshot.mjs --sidecar-only)
const side = (file, o) => fs.writeFileSync(path.join(HERE, 'snapshots', file + '.provenance.json'), JSON.stringify(Object.assign(o, { writtenSha256: sha(fs.readFileSync(path.join(HERE, 'snapshots', file))), writtenBytes: fs.statSync(path.join(HERE, 'snapshots', file)).size }), null, 2) + '\n');
const hz = ['horizons-orex-tag-10s.txt', 'horizons-orex-tag-contact-0.5s.txt', 'horizons-bennu-helio-tag.txt', 'horizons-orex-geo-tag.txt'];
side('tag-recon.js', { repo: 'https://ssd.jpl.nasa.gov/api/horizons.api', path: 'COMMAND=-64 CENTER=@2101955 VECTORS ICRF TDB 2020-10-20 17:00-22:00 (10 s) and 21:51:00-04 (0.5 s); COMMAND=2101955 CENTER=@10; OBSERVER -64 from 500@399 quantity 21', commit: 'retrieved 2026-10-31', retrieved: '2026-10-31',
  sourceSha256: Object.fromEntries(hz.map((f) => [f, sha(rd(f))])), license: 'JPL Horizons ephemerides (NASA/JPL, public)', mode: 'derived',
  note: 'derived by build-data.mjs: ' + kept.length + ' rows of the descent (every 600 s on the 4-h leg, every 20 s after Checkpoint, rows bracketing each burn, the last descent-segment row), km to m; sun = idea 42 closing.js accel() at each row (ideas/42-closing-in at the bank\'s HEAD); light time row 21:50 UTC' });
side('tag-sources.js', { repo: 'NASA Technical Reports Server (ntrs.nasa.gov), nasa.gov, science.nasa.gov, JPL Horizons', path: 'NTRS 20210025295, 20200000774, 20140017837, 20220006342, 20220000264; nasa.gov pages of 2020-10-21, 2021-04-15, 2022-07-07; science.nasa.gov blog 2024-02-15; Horizons -64 header', commit: 'retrieved 2026-10-31', retrieved: '2026-10-31',
  sourceSha256: docSha, license: 'NASA reports and pages are US government works; Walsh et al. 2022 (Space Sci. Rev.) is CC BY 4.0; facts quoted with citation', mode: 'transcribed',
  note: 'hand-transcribed figures; build-data.mjs checked all ' + quotes + ' quotes appear in their documents (pdftotext -layout for PDFs, tags stripped for HTML, whitespace normalised)' });
console.log('quotes checked:', quotes, '| recon rows:', kept.length, '| contact t', D.contact.t, 'jump', D.contact.jump_m, 'm | light time', D.lightTime_min_at_2150utc, 'min');
