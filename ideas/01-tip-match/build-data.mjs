#!/usr/bin/env node
// Wraps the rev_a.json snapshot and its provenance sidecar as a classic script so index.html can
// read the canon when opened from file:// (fetch() of a sibling JSON file is blocked there).
// Nothing is retyped: the JSON bytes are parsed and re-serialised; a test checks the result is
// deep-equal to snapshots/rev_a.json. After running this, record its provenance with
//   node tools/snapshot.mjs /home/user/skyhook params/rev_a.json ideas/01-tip-match/snapshots/rev_a.data.js --sidecar-only --note "..."
// From the bank root: node ideas/01-tip-match/build-data.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const src = path.join(here, 'snapshots', 'rev_a.json');
const side = path.join(here, 'snapshots', 'rev_a.json.provenance.json');
const dest = path.join(here, 'snapshots', 'rev_a.data.js');

const data = JSON.parse(fs.readFileSync(src, 'utf8'));
const provenance = JSON.parse(fs.readFileSync(side, 'utf8'));
const out = `// Generated by build-data.mjs from snapshots/rev_a.json and its provenance sidecar. Do not edit.
// Skyhook params/rev_a.json @ ${provenance.commit} (sha256 ${provenance.sourceSha256}).
(function (root, factory) {
  if (typeof module === 'object' && module.exports) module.exports = factory();
  else root.REV_A = factory();
})(typeof self !== 'undefined' ? self : this, function () {
  return {
    data: ${JSON.stringify(data, null, 1).replace(/\n/g, '\n    ')},
    provenance: ${JSON.stringify(provenance, null, 1).replace(/\n/g, '\n    ')}
  };
});
`;
fs.writeFileSync(dest, out);
console.log(`wrote ${path.relative(process.cwd(), dest)} (${out.length} bytes) from ${provenance.path} @ ${String(provenance.commit).slice(0, 7)}`);
