#!/usr/bin/env node
// Builds the two classic-script data modules index.html reads from file:// (fetch() of a sibling
// JSON file is blocked there). Nothing is retyped: numbers are parsed out of the snapshot copies
// or the source checkout, and a test re-derives each one and compares.
//
// 1. snapshots/rev_a.data.js wraps snapshots/rev_a.json and its sidecar (Skyhook canon). Its
//    sidecar is written afterwards with
//      node tools/snapshot.mjs /home/user/skyhook params/rev_a.json ideas/01-tip-match/snapshots/rev_a.data.js --sidecar-only --note "..."
// 2. With --aster <asteroid-mining-planner checkout>, snapshots/aster.data.js is derived from
//      - snapshots/aster_physics_constants.ts (a tools/snapshot.mjs copy of src/physics/constants/index.ts):
//        GM_sun, AU and the Earth row (a, e) of the Standish elements, for the upper v∞ bound;
//      - snapshots/aster_delta-v.ts (a copy of src/v2/porkchop/delta-v.ts): EARTH_MU_KM3_PER_S2 and
//        LEO_PARKING_RADIUS_KM, to back v∞ out of an Earth-entry speed;
//      - the JPL NHATS records committed in tests/fixtures/v2/nhats-validation-targets and
//        tests/fixtures/v2/oq7-nhats-coorbital: des, fullname and min_dv_traj.{v_arr_earth, dec_arr}
//        kept as the strings the API returned; API error records are listed, not kept;
//      - three altitudes that exist only in prose, typed here with their file, line and commit
//        (CITED below).
//    Its sidecar is written here in tools/snapshot.mjs's schema, because the tool has no
//    multi-file mode; every fixture file's committed blob is checked against the bytes read.
// From the bank root:
//   node ideas/01-tip-match/build-data.mjs [--aster /home/user/asteroid-mining-planner]
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const snap = (f) => path.join(here, 'snapshots', f);
const sha256 = (buf) => crypto.createHash('sha256').update(buf).digest('hex');

function umd(globalName, header, obj) {
  return `${header}
(function (root, factory) {
  if (typeof module === 'object' && module.exports) module.exports = factory();
  else root.${globalName} = factory();
})(typeof self !== 'undefined' ? self : this, function () {
  return ${JSON.stringify(obj, null, 1).replace(/\n/g, '\n  ')};
});
`;
}

// ------------------------------------------------------------------ 1. rev_a.data.js (unchanged format)
{
  const data = JSON.parse(fs.readFileSync(snap('rev_a.json'), 'utf8'));
  const provenance = JSON.parse(fs.readFileSync(snap('rev_a.json.provenance.json'), 'utf8'));
  const out = `// Generated by build-data.mjs from snapshots/rev_a.json and its provenance sidecar. Do not edit.
// Skyhook params/rev_a.json @ ${provenance.commit} (sha256 ${provenance.sourceSha256}).
(function (root, factory) {
  if (typeof module === 'object' && module.exports) module.exports = factory();
  else root.REV_A = factory();
})(typeof self !== 'undefined' ? self : this, function () {
  return {
    data: ${JSON.stringify(data, null, 1).replace(/\n/g, '\n    ')},
    provenance: ${JSON.stringify(provenance, null, 1).replace(/\n/g, '\n    ')}
  };
});
`;
  fs.writeFileSync(snap('rev_a.data.js'), out);
  console.log(`wrote snapshots/rev_a.data.js (${out.length} bytes) from ${provenance.path} @ ${String(provenance.commit).slice(0, 7)}`);
}

// ------------------------------------------------------------------ 2. aster.data.js
const asterArg = process.argv.indexOf('--aster');
if (asterArg === -1) process.exit(0);
const repo = path.resolve(process.argv[asterArg + 1] || '');
const git = (...args) => execFileSync('git', args, { cwd: repo, encoding: 'utf8' }).trim();

// Constants parsed out of the snapshot copies (the copies' own sidecars carry commit and blob).
function tsNumber(text, name, file) {
  const m = new RegExp(`export const ${name}\\s*=\\s*([0-9_.eE+-]+)`).exec(text);
  if (!m) throw new Error(`${file}: no "export const ${name} = <number>"`);
  return Number(m[1].replace(/_/g, ''));
}
const physTs = fs.readFileSync(snap('aster_physics_constants.ts'), 'utf8');
const dvTs = fs.readFileSync(snap('aster_delta-v.ts'), 'utf8');
const earthRow = /\/\/ Earth\s*\n\s*\[\s*([0-9.]+),\s*[-0-9.]+,\s*([0-9.]+),/.exec(physTs);
if (!earthRow) throw new Error('aster_physics_constants.ts: no "// Earth" row in PLANETS');
const lineOf = (text, needle) => text.split('\n').findIndex((l) => l.includes(needle)) + 1;

// Altitudes Aster states only in prose; each is typed once, here, with its citation.
const CITED = {
  leo_parking_altitude_km: { value: 200, cite: 'src/v2/app/porkchop/main.ts:981', quote: '200 km circular LEO (r = ${LEO_PARKING_RADIUS_KM.toFixed(3)} km)' },
  nhats_entry_altitude_km: { value: 125, cite: 'src/v2/research/slice-11-porkchop/perplexity-jpl-trajectory-browser-nhats.md:42', quote: 'Earth atmospheric entry speed ≤ 12 km/s at 125 km altitude' },
  browser_reentry_altitude_km: { value: 200, cite: 'src/v2/research/slice-11-porkchop/perplexity-jpl-trajectory-browser-nhats.md:17', quote: 'it assumes 200 km LEO injection plus 200 km Earth inertial reentry for its trajectory model' },
};
// The quotes must still be on those lines at the checkout's HEAD, or the build stops.
for (const [k, c] of Object.entries(CITED)) {
  const [file, line] = c.cite.split(':');
  const text = fs.readFileSync(path.join(repo, file), 'utf8').split('\n')[Number(line) - 1] || '';
  if (!text.includes(c.quote)) throw new Error(`${k}: ${c.cite} no longer says "${c.quote}"`);
}

const DIRS = ['tests/fixtures/v2/nhats-validation-targets', 'tests/fixtures/v2/oq7-nhats-coorbital'];
const records = [];
const byDes = new Map();
const skipped = [];
const dirs = [];
let filesRead = 0;
let allMatch = true;
for (const dir of DIRS) {
  const committed = new Map(
    git('ls-tree', 'HEAD', `${dir}/`)
      .split('\n')
      .filter(Boolean)
      .map((l) => {
        const [meta, p] = l.split('\t');
        return [p, meta.split(' ')[2]];
      })
  );
  const names = fs.readdirSync(path.join(repo, dir)).filter((f) => f.endsWith('.json')).sort();
  const read = git('hash-object', ...names.map((f) => `${dir}/${f}`)).split('\n');
  names.forEach((f, i) => {
    filesRead++;
    const rel = `${dir}/${f}`;
    if (committed.get(rel) !== read[i]) allMatch = false;
    const j = JSON.parse(fs.readFileSync(path.join(repo, rel), 'utf8'));
    const t = j && j.min_dv_traj;
    if (!t) {
      skipped.push({ file: rel, reason: j && j.error ? `API error record: ${String(j.error).slice(0, 80)}` : 'no min_dv_traj' });
      return;
    }
    const prev = byDes.get(j.des);
    if (prev) {
      prev.files.push(rel);
      if (prev.v_arr_earth !== t.v_arr_earth || prev.dec_arr !== t.dec_arr) prev.conflict = true;
      return;
    }
    const rec = { des: j.des, fullname: String(j.fullname || '').trim(), v_arr_earth: t.v_arr_earth, dec_arr: t.dec_arr, computed: j.computed, files: [rel] };
    byDes.set(j.des, rec);
    records.push(rec);
  });
  dirs.push({ path: dir, committedTree: git('rev-parse', `HEAD:${dir}`), files: names.length });
}

const commit = git('rev-parse', 'HEAD');
const data = {
  helio: {
    gm_sun_m3s2: tsNumber(physTs, 'GM_sun', 'aster_physics_constants.ts'),
    au_m: tsNumber(physTs, 'AU', 'aster_physics_constants.ts'),
    earth_a_au: Number(earthRow[1]),
    earth_e: Number(earthRow[2]),
    source: `snapshots/aster_physics_constants.ts (src/physics/constants/index.ts:${lineOf(physTs, 'export const GM_sun')},${lineOf(physTs, 'export const AU ')},${lineOf(physTs, '// Earth') + 1}, Standish 1992 elements at J2000)`,
  },
  porkchop: {
    earth_mu_km3s2: tsNumber(dvTs, 'EARTH_MU_KM3_PER_S2', 'aster_delta-v.ts'),
    leo_parking_radius_km: tsNumber(dvTs, 'LEO_PARKING_RADIUS_KM', 'aster_delta-v.ts'),
    source: `snapshots/aster_delta-v.ts (src/v2/porkchop/delta-v.ts:${lineOf(dvTs, 'EARTH_MU_KM3_PER_S2 =')}-${lineOf(dvTs, 'LEO_PARKING_RADIUS_KM =')})`,
  },
  cited: CITED,
  nhats: {
    source: 'NASA/JPL NHATS Data API records committed as Aster test fixtures (external data, not computed by Aster)',
    dirs,
    files_read: filesRead,
    records,
    skipped,
  },
  provenance: { repo: git('remote', 'get-url', 'origin'), commit, commitDate: git('log', '-1', '--format=%cI') },
};
const header = `// Generated by build-data.mjs --aster from the Aster checkout @ ${commit}. Do not edit.
// Aster constants (from the two .ts snapshot copies) and the JPL NHATS fixture records' Earth-entry speeds.`;
const out = umd('ASTER_DATA', header, data);
fs.writeFileSync(snap('aster.data.js'), out);
const sidecar = {
  repo: data.provenance.repo,
  path: DIRS.join(' + '),
  commit,
  commitDate: data.provenance.commitDate,
  pathLastChanged: git('log', '-1', '--format=%h %cI', '--', ...DIRS),
  committedTree: dirs.map((d) => `${d.path}=${d.committedTree}`).join(' '),
  sourceFiles: filesRead,
  copiedAt: new Date().toISOString(),
  mode: 'derived',
  note: `derived by build-data.mjs --aster: des, fullname and min_dv_traj.{v_arr_earth, dec_arr} of every NHATS fixture record (${records.length} unique bodies from ${filesRead} files; ${skipped.length} API error records listed, not kept; duplicates folded with their file names), plus GM_sun, AU and Earth's a, e parsed from snapshots/aster_physics_constants.ts and EARTH_MU_KM3_PER_S2, LEO_PARKING_RADIUS_KM from snapshots/aster_delta-v.ts, plus three cited altitudes whose quoted text the build re-checks. Sidecar written by build-data.mjs in tools/snapshot.mjs's schema (the tool has no multi-file mode).`,
  readMatchesCommitted: allMatch,
  writtenSha256: sha256(Buffer.from(out)),
  writtenBytes: Buffer.byteLength(out),
};
fs.writeFileSync(snap('aster.data.js.provenance.json'), `${JSON.stringify(sidecar, null, 2)}\n`);
console.log(`wrote snapshots/aster.data.js (${Buffer.byteLength(out)} bytes): ${records.length} NHATS bodies from ${filesRead} files, ${skipped.length} skipped; read bytes match committed: ${allMatch}`);
