#!/usr/bin/env node
// Builds this module's data from the primary sources fetched by oracle/fetch-sources.sh, and the two handoffs of idea 44.
//   node ideas/45-dig/build-data.mjs <dir of fetched sources>   writes snapshots/dig-sources.js, snapshots/sun-ephem.js,
//                                                               oracle/horizons-bennu-sun.json and their sidecars
//   node ideas/45-dig/build-data.mjs --handoffs                 writes snapshots/touch-handoff.js (idea 44's committed
//                                                               handoff, wrapped) and snapshots/touch-bennu-handoff.js
//                                                               (idea 44's own kernel run on its Bennu case)
//   node ideas/45-dig/build-data.mjs --sample                   writes handoff.json (this page's defaults on the chain)
// Every figure transcribed below is checked to be in its source's text (whitespace-normalised) before it is written:
// a figure that is not found stops the build. Nothing here runs at page time.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const BANK = path.resolve(HERE, '..', '..');
const require = createRequire(import.meta.url);
const sha = (b) => crypto.createHash('sha256').update(b).digest('hex');
const norm = (s) => s.replace(/\s+/g, ' ');
const RETRIEVED = '2026-11-01';

function wrap(name, comment, data) {
  return `/* ${comment}\n * GENERATED by ideas/45-dig/build-data.mjs; do not edit. Classic script (window.${name}) and require(). */\n(function (root) {\n  var D = ${JSON.stringify(data)};\n  if (typeof module === 'object' && module.exports) module.exports = D;\n  else root.${name} = D;\n})(typeof self !== 'undefined' ? self : this);\n`;
}
function writeWithSidecar(rel, text, sidecar) {
  const p = path.join(HERE, rel);
  fs.writeFileSync(p, text);
  sidecar.writtenSha256 = sha(Buffer.from(text));
  sidecar.writtenBytes = Buffer.byteLength(text);
  fs.writeFileSync(p + '.provenance.json', JSON.stringify(sidecar, null, 2) + '\n');
  console.log('wrote', rel, Buffer.byteLength(text), 'bytes');
}

