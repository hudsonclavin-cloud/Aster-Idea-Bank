#!/usr/bin/env node
// Writes oracle/cases.json: the inputs oracle/window_oracle.py needs to check this kernel independently.
//   epochs   UTC instants at which to compare Earth orientation (the oracle derives its own TT and UT1 from UTC with
//            ERFA's own leap-second table, not NAIF's)
//   window   the Apophis preset's site, asymptote and corridor, and the kernel's no-J2 window edges, for a brute-force
//            scan with the full IAU 2006/2000A Earth orientation
//   coast    the kernel's insertion state and departure time (mean frame of date) for the default launch, for an
//            independent integration (scipy DOP853) with the same force model, and with J3 and J4 added
// Run from the bank root: node ideas/37-window/oracle/build-cases.mjs
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
const here = path.dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const L = require(path.join(here, '..', 'load.cjs'));
const W = L.W;

export function cases() {
  const h36 = L.as512Handoff36();
  const st = W.importClosedLoop(h36);
  const set = W.defaults(st.siteId), spec = W.apophisSpec();
  const R = W.compute(st, spec, set, { perf: false });
  const s = R.launch;
  const epochs = ['1972-12-07T02:53:00Z', '1972-12-07T05:33:00Z', '2016-09-08T23:05:00Z', '2026-07-02T02:50:50Z', '2033-03-20T12:00:00Z', '2040-12-31T18:00:00Z'];
  return {
    note: 'Generated by oracle/build-cases.mjs from the kernel; inputs for oracle/window_oracle.py.',
    epochs: epochs.map((e) => { const T = W.orient(W.parseUtc(e)); return { utc: e, ttMinusUtc: T.ttMinusUtc, kernel: { era: W.era(T.du), gmst: T.gmst, P: T.P } }; }),
    window: { latDeg: st.latDeg, lonDeg: set.lonDeg, corridor: set.corridor, S_icrf: R.asym.S, dayUtc: spec.dateUtc,
      kernelNoJ2: R.windowsNoJ2.map((w) => ({ open: w.openMs / 1000, close: w.closeMs / 1000, azOpen: w.azOpenDeg, azClose: w.azCloseDeg })) },
    coast: { mu: W.constants.MU, j2: W.constants.J2, rj2: W.constants.RJ2, wgs84: L.NAIF.wgs84, r0: s.ins.r, v0: s.ins.v, T: s.ev.t, kernelR: s.ev.r, kernelV: s.ev.v, S_mod: s.S, c3: R.asym.c3, dt: set.dt },
  };
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const c = cases();
  fs.writeFileSync(path.join(here, 'cases.json'), JSON.stringify(c, null, 1) + '\n');
  console.log('wrote oracle/cases.json:', c.epochs.length, 'epochs,', c.window.kernelNoJ2.length, 'windows, coast of', c.coast.T.toFixed(1), 's');
}
