#!/usr/bin/env node
// Derives snapshots/aster-parking.js, the one generated snapshot of this module: Aster's assumed parking orbit radius,
// parsed out of the verbatim snapshots/aster-delta-v.ts.txt (Aster src/v2/porkchop/delta-v.ts at 62ddb17), as a classic
// script the page can load. Nothing is typed by hand.
// Run from the bank root: node ideas/36-closed-loop/build-data.mjs   (then the sidecar command it prints)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const here = path.dirname(fileURLToPath(import.meta.url));
const src = fs.readFileSync(path.join(here, 'snapshots', 'aster-delta-v.ts.txt'), 'utf8');
const m = /export const LEO_PARKING_RADIUS_KM = ([\d_.]+);/.exec(src);
if (!m) throw new Error('LEO_PARKING_RADIUS_KM not found in the delta-v.ts snapshot');
const km = Number(m[1].replace(/_/g, ''));
const D = { leoParkingRadius_m: km * 1000, source: 'Aster src/v2/porkchop/delta-v.ts LEO_PARKING_RADIUS_KM = ' + km + ' km (snapshots/aster-delta-v.ts.txt): the circular parking orbit Aster\'s porkchop computes injection delta-v from' };
const out = `/* GENERATED by ideas/36-closed-loop/build-data.mjs from snapshots/aster-delta-v.ts.txt (verbatim Aster file at 62ddb17);
 * do not edit. Classic script (window.AsterParking) and require(). SI units. */
(function (root) {
  var D = ${JSON.stringify(D, null, 2).replace(/\n/g, '\n  ')};
  if (typeof module === 'object' && module.exports) module.exports = D;
  else root.AsterParking = D;
})(typeof self !== 'undefined' ? self : this);
`;
fs.writeFileSync(path.join(here, 'snapshots', 'aster-parking.js'), out);
console.log('wrote snapshots/aster-parking.js:', D.leoParkingRadius_m, 'm');
console.log('sidecar: node tools/snapshot.mjs /home/user/asteroid-mining-planner src/v2/porkchop/delta-v.ts ideas/36-closed-loop/snapshots/aster-parking.js --sidecar-only --note "derived by build-data.mjs: LEO_PARKING_RADIUS_KM parsed from snapshots/aster-delta-v.ts.txt"');
