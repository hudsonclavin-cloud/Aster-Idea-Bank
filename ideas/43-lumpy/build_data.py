def ck_records(path):
    h = sp.dafopr(path)
    sp.dafbfs(h)
    ep, rec = [], []
    while sp.daffna():
        dc, ic = sp.dafus(sp.dafgs(), 2, 6)
        assert ic[0] == -2099942000 and ic[2] == 3 and ic[3] == 1, ic      # type 3 with angular velocity
        assert sp.frmnam(int(ic[1])) == 'ECLIPJ2000', ic                   # the segment's base frame: ecliptic, not J2000
        b, e = int(ic[4]), int(ic[5])
        n = int(sp.dafgda(h, e, e)[0])
        rec.append(np.array(sp.dafgda(h, b, b + 7 * n - 1)).reshape(n, 7))
        ep.append(np.array(sp.dafgda(h, b + 7 * n, b + 8 * n - 1)))
    comments = sp.dafec(h, 3000, 1000)[1]
    sp.dafcls(h)
    return np.concatenate(ep), np.concatenate(rec), comments


