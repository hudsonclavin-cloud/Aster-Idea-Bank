#!/usr/bin/env python3
"""Build idea 43's snapshots from the primary sources that oracle/fetch-sources.sh downloads.

    python3 build_data.py <directory with the downloads>

Needs spiceypy and numpy (a throw-away venv; the page and the node tests need neither). Writes, under snapshots/:

  shapes.js        the two shape models as little-endian base64: vertices int32 millimetres in the body frame,
                   plates uint16 vertex indices (0-based, counter-clockwise seen from outside).
                   Apophis: the DSK's 2000 vertices and 3996 plates unchanged (its km values have 6 decimals, so mm
                   integers are exact; checked below). Bennu: the OLA v021 12.6 m DSK is an implicitly-connected
                   quadrilateral (ICQ) grid, 6 faces x 33 x 33 vertices; every second grid vertex (17 x 17 per face)
                   is kept, welded where cube faces meet, and triangulated the way the DSK's own first plates are, so
                   the shipped model is the 25 m (q = 16) subsample of the published vertices, rounded to 1 mm.
  attitude.js      Apophis: the CK's own samples (quaternion and angular velocity, exactly as stored) every 20 days
                   from 2026-01-01 to the 2029 Earth encounter, and the Pravec et al. (2014) parameters from the CK's
                   comment area. Bennu: pole and prime meridian from bennu_v17.tpc's data section.
  geophysics.js    Barnouin et al. 2019 Table 1 and Scheeres et al. 2020 Table 1, transcribed from the PMC JATS XML.
  orbit-b.js       JPL Horizons: OSIRIS-REx relative to Bennu and Bennu about the Sun, 2019-06-19 to 06-22, every 2 h.

Each gets a hand-written <file>.provenance.json (repo, path, commit, retrieved, sourceSha256, license, note,
writtenSha256), as the series brief asks for fetched data.
"""
import base64, hashlib, json, os, re, sys
import numpy as np
import spiceypy as sp

SRC = sys.argv[1] if len(sys.argv) > 1 else '.'
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, 'snapshots')
RETRIEVED = '2026-10-31'
NAIF = 'https://naif.jpl.nasa.gov'


def sha(path):
    return hashlib.sha256(open(path, 'rb').read()).hexdigest()


def src(name):
    return os.path.join(SRC, name)


def write_js(name, glob, data, header, sidecar):
    body = json.dumps(data, separators=(',', ':'))
    text = ('/* ' + header + '\n * GENERATED by ideas/43-lumpy/build_data.py from the downloads of oracle/fetch-sources.sh; do not edit.'
            ' Classic script (window.' + glob + ') and require(). */\n(function (root) {\n  var D = ' + body +
            ';\n  if (typeof module === \'object\' && module.exports) module.exports = D;\n  else root.' + glob + ' = D;\n'
            '})(typeof self !== \'undefined\' ? self : this);\n')
    path = os.path.join(OUT, name)
    open(path, 'w').write(text)
    sidecar = dict(sidecar)
    sidecar.setdefault('commit', 'retrieved ' + RETRIEVED)
    sidecar['retrieved'] = RETRIEVED
    sidecar['writtenSha256'] = sha(path)
    sidecar['writtenBytes'] = os.path.getsize(path)
    open(path + '.provenance.json', 'w').write(json.dumps(sidecar, indent=2) + '\n')
    print('wrote', name, os.path.getsize(path), 'bytes')


def b64(arr):
    return base64.b64encode(arr.tobytes()).decode('ascii')


def load_dsk(path):
    h = sp.dasopr(path)
    dla = sp.dlabfs(h)
    dsc = sp.dskgd(h, dla)
    nv, npl = sp.dskz02(h, dla)
    v = np.array(sp.dskv02(h, dla, 1, nv))
    p = np.array(sp.dskp02(h, dla, 1, npl)) - 1
    sp.dascls(h)
    return v, p, dsc


def check_closed(p):
    """Every directed edge once and its reverse once: a closed, consistently wound triangle mesh."""
    e = {}
    for a, b, c in p:
        for x, y in ((a, b), (b, c), (c, a)):
            e[(x, y)] = e.get((x, y), 0) + 1
    bad = sum(1 for (x, y), n in e.items() if n != 1 or e.get((y, x), 0) != 1)
    nv = len(set(p.ravel()))
    return bad, nv - len(e) // 2 + len(p)


def volume(v, p):
    a, b, c = v[p[:, 0]], v[p[:, 1]], v[p[:, 2]]
    return np.einsum('ij,ij->i', a, np.cross(b, c)).sum() / 6


