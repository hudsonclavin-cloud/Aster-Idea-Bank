def shapes():
    out = {}
    fa = 'apophis_g_25000mm_rad_obj_0000n00000_v001.bds'
    v, p, dsc = load_dsk(src(fa))
    mm = v * 1e6
    assert np.abs(mm - np.round(mm)).max() < 1e-6, 'Apophis DSK is not on a 1 mm grid'
    vi = np.round(mm).astype('<i4')
    bad, chi = check_closed(p)
    assert bad == 0 and chi == 2, ('Apophis mesh not closed', bad, chi)
    out['apophis'] = {
        'key': 'apophis', 'designation': '99942', 'name': '99942 Apophis', 'label': 'Apophis (radar, 25 m plates)',
        'model': 'Apophis RAD v001 (NAIF DSK surface 425000001)', 'frame': 'APOPHIS_CK (NAIF -2099942000): +z the short axis, origin the centre of mass, principal axes',
        'reference': 'Brozovic et al. (2018), Goldstone and Arecibo radar observations of (99942) Apophis in 2012-2013, Icarus 300, 115-128 (orx_shape_v04.tf)',
        'dsk': fa, 'dskSha256': sha(src(fa)), 'resolution_m': 25, 'nv': int(len(vi)), 'nf': int(len(p)),
        'transform': 'none: the DSK vertices (km, 6 decimals) as integer millimetres, the plates as stored',
        'vertices_b64': b64(vi.ravel()), 'faces_b64': b64(p.astype('<u2').ravel())}

    fb = 'bennu_g_12600mm_alt_obj_0000n00000_v021.bds'
    v, p, dsc = load_dsk(src(fb))
    q = 32
    Q = q + 1
    assert len(v) == 6 * Q * Q and len(p) == 6 * q * q * 2, 'Bennu DSK is not an ICQ q=32 grid'
    # the DSK's own first plates fix the grid's triangulation: (0,0)-(1,1)-(1,0) and (0,0)-(0,1)-(1,1) in (i, j)
    assert list(p[0]) == [0, Q + 1, 1] and list(p[1]) == [0, Q, Q + 1], p[:2]
    idx = lambda f, i, j: f * Q * Q + j * Q + i
    key = np.round(v * 1e6).astype(np.int64)                 # weld by mm position (seam copies are identical)
    uniq, inv = np.unique(key, axis=0, return_inverse=True)
    inv = inv.ravel()
    sub = []
    for f in range(6):
        for J in range(0, q, 2):
            for I in range(0, q, 2):
                a, b, c, d = idx(f, I, J), idx(f, I + 2, J), idx(f, I + 2, J + 2), idx(f, I, J + 2)
                sub.append((inv[a], inv[c], inv[b]))
                sub.append((inv[a], inv[d], inv[c]))
    sub = np.array(sub)
    used = np.unique(sub.ravel())
    remap = -np.ones(len(uniq), dtype=np.int64)
    remap[used] = np.arange(len(used))
    p16 = remap[sub]
    v16 = uniq[used].astype('<i4')
    bad, chi = check_closed(p16)
    assert bad == 0 and chi == 2, ('Bennu q16 mesh not closed', bad, chi)
    assert volume(v16.astype(float), p16) > 0, 'Bennu q16 wound inside-out'
    out['bennu'] = {
        'key': 'bennu', 'designation': '101955', 'name': '101955 Bennu', 'label': 'Bennu (OLA altimetry, 25 m subsample)',
        'model': 'Bennu ALT v021 12.6 m (NAIF DSK surface 312600021), every second ICQ vertex',
        'frame': 'IAU_BENNU (NAIF 10106, bennu_v17.tpc): +z the spin pole, origin the centre of mass',
        'reference': 'Daly et al. (2020), Hemispherical differences in the shape and topography of asteroid (101955) Bennu, Sci. Adv. 6, eabd3649 (orx_shape_v04.tf)',
        'dsk': fb, 'dskSha256': sha(src(fb)), 'resolution_m': 25.2, 'nv': int(len(v16)), 'nf': int(len(p16)),
        'transform': 'ICQ q=32 -> q=16: vertices (i, j) with i, j even on each of the 6 cube faces (17 x 17), welded at the cube edges, triangulated as the DSK triangulates (diagonal (i,j)-(i+1,j+1)); rounded to 1 mm',
        'source_nv': int(len(v)), 'source_nf': int(len(p)), 'source_unique_vertices': int(len(uniq)),
        'vertices_b64': b64(v16.ravel()), 'faces_b64': b64(p16.astype('<u2').ravel())}
    write_js('shapes.js', 'LumpyShapes', out, 'Asteroid shape models for idea 43 (Lumpy): Apophis (radar) and Bennu (OSIRIS-REx laser altimetry), from NAIF DSKs.', {
        'repo': NAIF + '/pub/naif/ORX/kernels/dsk/', 'path': fa + ' and ' + fb,
        'sourceSha256': {fa: sha(src(fa)), fb: sha(src(fb))},
        'license': 'NASA/JPL NAIF SPICE kernels delivered by the OSIRIS-REx project: US government work, public domain (no copyright)',
        'note': 'Apophis: the DSK unchanged (2000 vertices, 3996 plates, mm integers exact). Bennu: the q=32 ICQ grid subsampled to q=16 (1538 vertices, 3072 plates) and rounded to 1 mm; the oracle (oracle/oracle.py) measures what the subsample changes against the full 12288-plate DSK.'})


