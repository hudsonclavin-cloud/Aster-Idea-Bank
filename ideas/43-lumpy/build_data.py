def jats_table(path, n=0):
    x = open(path, encoding='utf-8').read()
    tw = re.findall(r'<table-wrap[^>]*>(.*?)</table-wrap>', x, re.S)[n]
    rows = []
    for row in re.findall(r'<tr[^>]*>(.*?)</tr>', tw, re.S):
        cells = [re.sub(r'\s+', ' ', re.sub(r'<[^>]+>', '', c)).strip() for c in re.findall(r'<t[hd][^>]*>(.*?)</t[hd]>', row, re.S)]
        rows.append(cells)
    cap = re.sub(r'\s+', ' ', re.sub(r'<[^>]+>', ' ', re.search(r'<caption>(.*?)</caption>', tw, re.S).group(1))).strip()
    foot = re.search(r'<table-wrap-foot>(.*?)</table-wrap-foot>', tw, re.S)
    return cap, rows, (re.sub(r'\s+', ' ', re.sub(r'<[^>]+>', ' ', foot.group(1))).strip() if foot else None)


def sci(s):
    """'1.875791 × 10−2' -> 0.01875791"""
    s = s.replace('−', '-').replace(' ', '')
    m = re.match(r'^([-0-9.]+)(?:×10([-0-9]+))?$', s)
    return float('%.10g' % (float(m.group(1)) * (10.0 ** int(m.group(2)) if m.group(2) else 1)))


