#!/usr/bin/env node
// Writes snapshots/window-as512-apophis.js: idea 37's handoff for the departure its page opens on (the Saturn V AS-512
// guided to Apollo 17's parking orbit by idea 36, taken to Aster's Apophis asymptote of 2 July 2026 from Pad 39A, Aster's
// corridor, launching at the window's opening), computed by idea 37's committed kernel, unmodified, through its own
// loader (ideas/37-window/load.cjs, which loads ideas 33 to 36). This module cannot re-fly that chain itself (the
// earlier kernels are 307 KB), so the handoff is kept as data; burnout.test.mjs checks the file is what idea 37's kernel
// gives, and the page reads it as its default. Run from the bank root: node ideas/38-burn-out/build-data.mjs
// Then: node tools/snapshot.mjs /home/user/Aster-Idea-Bank ideas/37-window/window.js ideas/38-burn-out/snapshots/window-as512-apophis.js --sidecar-only --note "..."
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
const here = path.dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
export const PRODUCED = '2026-10-31T12:00:00Z';
/** Idea 37's page default, as its app.js builds it: idea 36's AS-512 handoff, Aster's Apophis asymptote, the defaults. */
export function window37Default() {
  const L = require(path.join(here, '..', '37-window', 'load.cjs'));
  const W = L.W, h36 = L.as512Handoff36(PRODUCED), st = W.importClosedLoop(h36);
  if (st.refusal) throw new Error(st.refusal.reason);
  const set = W.defaults(st.siteId), spec = W.apophisSpec(), R = W.compute(st, spec, set);
  return W.makeHandoff(st, spec, set, R, { produced: PRODUCED });
}
export function asScript(h) {
  return '/* GENERATED by ideas/38-burn-out/build-data.mjs: idea 37\'s handoff for its page\'s default (Saturn V AS-512 to Aster\'s\n' +
    ' * Apophis asymptote, 2 July 2026), computed by idea 37\'s committed kernel. Do not edit. Classic script\n' +
    ' * (window.WINDOW_AS512_APOPHIS) and require(). */\n' +
    '(function (root) {\n  var D = ' + JSON.stringify(h) + ';\n' +
    '  if (typeof module === \'object\' && module.exports) module.exports = D;\n  else root.WINDOW_AS512_APOPHIS = D;\n})(typeof self !== \'undefined\' ? self : this);\n';
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const h = window37Default(), out = path.join(here, 'snapshots', 'window-as512-apophis.js');
  fs.writeFileSync(out, asScript(h));
  console.log('wrote', out, fs.statSync(out).size, 'bytes; departure', h.outputs.departure_point.value.utc, 'propellant', h.outputs.propellant_for_departure.value.toFixed(1), 'kg');
}
