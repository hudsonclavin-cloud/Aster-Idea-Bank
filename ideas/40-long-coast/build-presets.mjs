#!/usr/bin/env node
// Writes presets.js: one idea 39 transfer for each of the six bodies here (the six with a Horizons oracle), chosen by
// idea 39's own kernel (snapshots/lambert.js) as the least-C3 reliable cell of its porkchop over the stated ranges.
// Apophis is idea 39's default, Aster's DLA-oracle cell (the chain's transfer). The page rebuilds each 39 handoff from
// these settings with idea 39's kernel when the preset is chosen.
//   node ideas/40-long-coast/build-presets.mjs
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
const here = path.dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const { K } = require(path.join(here, 'load.cjs'));
const K39 = K.k39;
const RANGES = { depStartUtc: '2026-01-01', depEndUtc: '2028-01-01', tofMinDays: 120, tofMaxDays: 720, nDep: 120, nTof: 60, revs: [0, 1], objective: 'c3', site: 'cape' };
const out = [];
for (const b of K.k39.bodies.list) {
  const S = Object.assign(K39.defaults(), b.designation === '99942' ? {} : RANGES, { target: b.designation, selection: null });
  const R = K39.run(S, null);
  if (!R.transfer) { console.log(b.designation, 'no transfer', R.refusals.map((r) => r.applies_to)); continue; }
  const sel = { depTdb: R.selection.depTdb, tofS: R.selection.tofS, M: R.selection.M, branch: R.selection.branch, source: R.selection.source };
  const settings = Object.assign({}, S, { selection: sel });
  const R2 = K39.run(settings, null, { grid: false });
  const bad = R2.refusals.filter((r) => r.applies_to !== 'dynamics').map((r) => r.applies_to);
  out.push({ key: b.designation, label: b.name + ': ' + K39.utcOf(sel.depTdb).slice(0, 10) + ' + ' + (sel.tofS / 86400).toFixed(0) + ' d' + (sel.M ? ', ' + sel.M + ' rev' : ''), settings, c3_m2_s2: R2.transfer.sol.c3, refusals: bad, chosen: sel.source === 'aster_cell' ? 'Aster\'s DLA-oracle cell (idea 39\'s default and the chain\'s transfer)' : 'least-C3 reliable cell of idea 39\'s porkchop, departures ' + RANGES.depStartUtc + ' to ' + RANGES.depEndUtc + ', ' + RANGES.tofMinDays + '-' + RANGES.tofMaxDays + ' d, direct or one revolution' });
  console.log(b.designation, out[out.length - 1].label, 'C3', (R2.transfer.sol.c3 / 1e6).toFixed(3), bad);
}
const body = '/* Six idea 39 transfers, one per body with a Horizons oracle here. GENERATED by ideas/40-long-coast/build-presets.mjs\n * with idea 39\'s kernel; do not edit. Classic script (window.CoastPresets) and require(). */\n(function (root) {\n  var D = ' + JSON.stringify({ list: out }) + ";\n  if (typeof module === 'object' && module.exports) module.exports = D;\n  else root.CoastPresets = D;\n})(typeof self !== 'undefined' ? self : this);\n";
fs.writeFileSync(path.join(here, 'presets.js'), body);
console.log('wrote presets.js', body.length, 'bytes');
