if (hz.frame !== 'ICRF/J2000' || hz.timeScale !== 'TDB') throw new Error('unexpected Aster Horizons fixture metadata');
// Segment length, degree and rounding unit per body, chosen by the accuracy each needs as a perturber (README, How it
// works): the Moon passes close to a departing spacecraft, so it gets kilometres; the planets get tens to hundreds.
const ASTER_FITS = { moon: [32, 20, 1000, '301', '500@399'], mercury: [64, 18, 100000, '199', '@sun'], venus: [128, 16, 10000, '299', '@sun'], mars: [128, 16, 10000, '499', '@sun'] };
const asterBodies = {};
const moonWindows = {};
for (const [name, [segDays, deg, unit, id, center]] of Object.entries(ASTER_FITS)) {
  const T = hz.targets[name];
  if (T.targetId !== id || T.center !== center) throw new Error('unexpected ' + name + ' in Aster\'s fixture');
  const fit = fitBody(T.records, segDays, deg, unit);
  let worst = 0; T.records.forEach((r) => { const p = evalFit(fit, unit, r[0]); worst = Math.max(worst, norm3([p[0] - r[1] * 1000, p[1] - r[2] * 1000, p[2] - r[3] * 1000])); });
  const rec = { center: name === 'moon' ? 'earth' : 'sun', horizonsId: id, segDays, degree: deg, unit_m: unit, nSegments: fit.segs.length, jd0: fit.jd0, jdEnd: fit.jdEnd,
    segEdges: fit.segs.map((s) => s.a).concat([fit.jdEnd]), fit: { maxPosAtRecords_m: Math.round(worst) }, b36: b36(fit) };
  if (name === 'moon') {
    for (const w of ['2026', '2035']) {
      const H = horizonsRecords(F('horizons-moon-1h-' + w + '.json'));
      let wp = 0; H.forEach((r) => { const p = evalFit(fit, unit, r[0]); wp = Math.max(wp, norm3([p[0] - r[1] * 1000, p[1] - r[2] * 1000, p[2] - r[3] * 1000])); });
      moonWindows[w] = { from: H[0][0], to: H[H.length - 1][0], hourlyRecords: H.length, maxPos_m: Math.round(wp) };
      // a six-hourly excerpt for the tests (evaluated by the kernel's own evaluator there)
      moonWindows[w].excerpt = H.filter((r, i) => i % 24 === 7).map((r) => [r[0], r[1], r[2], r[3]]);
    }
    rec.fit.hourlyHorizons = Object.fromEntries(Object.entries(moonWindows).map(([k, v]) => [k, { from: v.from, to: v.to, hourlyRecords: v.hourlyRecords, maxPos_m: v.maxPos_m }]));
  }
  asterBodies[name] = rec;
  console.log(name, 'segments', fit.segs.length, 'worst at records', Math.round(worst), 'm', name === 'moon' ? JSON.stringify(rec.fit.hourlyHorizons) : '');
}
