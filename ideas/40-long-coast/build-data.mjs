function writeData(file, global, comment, data) {
  const body = '/* ' + comment + '\n * GENERATED by ideas/40-long-coast/build-data.mjs; do not edit. Classic script (window.' + global + ') and require(). */\n' +
    '(function (root) {\n  var D = ' + JSON.stringify(data) + ';\n' +
    "  if (typeof module === 'object' && module.exports) module.exports = D;\n  else root." + global + ' = D;\n})(typeof self !== \'undefined\' ? self : this);\n';
  fs.writeFileSync(snap(file), body);
  return body;
}
function handSidecar(file, info) {
  const buf = fs.readFileSync(snap(file));
  const side = Object.assign({ commit: 'retrieved ' + RETRIEVED, retrieved: RETRIEVED }, info, { writtenSha256: sha(buf), writtenBytes: buf.length });
  fs.writeFileSync(snap(file) + '.provenance.json', JSON.stringify(side, null, 1) + '\n');
}
function sidecarOnly(file, repo, srcPath, note) {
  execFileSync(process.execPath, [path.join(BANK, 'tools', 'snapshot.mjs'), repo, srcPath, path.join('ideas', '40-long-coast', 'snapshots', file), '--sidecar-only', '--note', note], { cwd: BANK, stdio: 'inherit' });
}

// ------------------------------------------------------------------ Chebyshev fitting (positions and velocities)
const cheb = (tau, deg) => { const T = [1, tau]; for (let k = 2; k <= deg; k++) T.push(2 * tau * T[k - 1] - T[k - 2]); return T.slice(0, deg + 1); };
const chebD = (tau, deg) => { const U = [1, 2 * tau]; for (let k = 2; k < deg; k++) U.push(2 * tau * U[k - 1] - U[k - 2]); const d = [0]; for (let k = 1; k <= deg; k++) d.push(k * U[k - 1]); return d; };
function lstsq(A, b) { // Householder QR least squares
  const m = A.length, nn = A[0].length, R = A.map((r) => r.slice()), y = b.slice();
  for (let k = 0; k < nn; k++) {
    let s = 0; for (let i = k; i < m; i++) s += R[i][k] * R[i][k];
    const alpha = (R[k][k] > 0 ? -1 : 1) * Math.sqrt(s), v = new Array(m).fill(0);
    v[k] = R[k][k] - alpha; for (let i = k + 1; i < m; i++) v[i] = R[i][k];
    let vv = 0; for (let i = k; i < m; i++) vv += v[i] * v[i];
    if (vv === 0) continue;
    for (let j = k; j < nn; j++) { let d = 0; for (let i = k; i < m; i++) d += v[i] * R[i][j]; d = 2 * d / vv; for (let i = k; i < m; i++) R[i][j] -= d * v[i]; }
    let d = 0; for (let i = k; i < m; i++) d += v[i] * y[i]; d = 2 * d / vv; for (let i = k; i < m; i++) y[i] -= d * v[i];
  }
  const x = new Array(nn).fill(0);
  for (let k = nn - 1; k >= 0; k--) { let s = y[k]; for (let j = k + 1; j < nn; j++) s -= R[k][j] * x[j]; x[k] = s / R[k][k]; }
  return x;
}
const DAY = 86400, J2000 = 2451545.0;
/** Fit records [[jdTdb, x, y, z, vx, vy, vz] km, km/s] with Chebyshev series of `deg` on `segDays`-day segments; the
 * coefficients rounded to whole multiples of unit_m and written base 36 (segments ';', axes '|', coefficients ','). */
function fitBody(records, segDays, deg, unit_m) {
  const jd0 = records[0][0], jdEnd = records[records.length - 1][0], step = records[1][0] - records[0][0];
  const segs = [], nPer = Math.round(segDays / step);
  for (let i0 = 0; i0 < records.length - 1; i0 += nPer) {
    const i1 = Math.min(i0 + nPer, records.length - 1), rows = records.slice(i0, i1 + 1);
    const a = rows[0][0], b = rows[rows.length - 1][0], half = (b - a) / 2;
    const dg = Math.min(deg, 2 * rows.length - 2), seg = [];
    for (let c = 0; c < 3; c++) {
      const A = [], y = [];
      rows.forEach((r) => {
        const tau = (r[0] - (a + half)) / half;
        A.push(cheb(tau, dg)); y.push(r[1 + c] * 1000);
        // d/dtau = v * half-interval; the velocity rows are divided by the half-interval (in days) so that a day's motion
        // weighs as much as a position (weighting them by the half-interval instead left 5-30 km residuals in the Moon)
        A.push(chebD(tau, dg).map((v) => v / half)); y.push(r[4 + c] * 1000 * DAY);
      });
      seg.push(lstsq(A, y).map((v) => Math.round(v / unit_m)));
    }
    segs.push({ a, b, seg });
  }
  return { jd0, jdEnd, segs };
}
/** The evaluator the kernel uses, here for measuring the fit (coast.js has its own copy of the same Clenshaw sum). */
function evalFit(fit, unit_m, jd) {
  let s = fit.segs.find((q) => jd >= q.a && jd <= q.b) || fit.segs[fit.segs.length - 1];
  const half = (s.b - s.a) / 2, tau = (jd - (s.a + half)) / half, out = [];
  for (let c = 0; c < 3; c++) { const T = cheb(tau, s.seg[c].length - 1); out.push(s.seg[c].reduce((acc, v, k) => acc + v * unit_m * T[k], 0)); }
  return out;
}
const b36 = (fit) => fit.segs.map((s) => s.seg.map((ax) => ax.map((v) => v.toString(36)).join(',')).join('|')).join(';');
function horizonsRecords(buf) {
  const r = JSON.parse(buf).result, i = r.indexOf('$$SOE'), j = r.indexOf('$$EOE');
  if (i < 0 || j < 0) throw new Error('no $$SOE/$$EOE in a Horizons response');
  return r.slice(i + 5, j).trim().split('\n').map((line) => { const p = line.split(',').map((s) => s.trim()); return [Number(p[0])].concat(p.slice(2, 8).map(Number)); });
}
function horizonsHeader(buf) { const r = JSON.parse(buf).result; return r.slice(0, r.indexOf('$$SOE')); }
const norm3 = (a) => Math.hypot(a[0], a[1], a[2]);

// ------------------------------------------------------------------ Aster's bodies: Moon, Mercury, Venus, Mars
