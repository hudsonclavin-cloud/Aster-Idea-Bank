#!/usr/bin/env node
// Derives this module's generated snapshots. Nothing here is typed from memory: every number is parsed out of a
// verbatim snapshot or computed by idea 34's committed kernel.
//
//   snapshots/pck00010-earth.txt   the BODY399 lines of Aster's vendored NAIF pck00010.tpc (Earth radii, prime
//                                  meridian rate), excerpted from /home/user/asteroid-mining-planner
//   snapshots/earth.js             Earth GM (Aster delta-v.ts), equatorial radius and rotation rate (pck00010),
//                                  launch sites (Aster feasibility.ts), parsed from the three verbatim snapshots
//   snapshots/data-json.js         one classic script holding idea 34's data: its five preset engine records in its
//                                  handoff format, its handoff for Saturn V AS-512 as flown (what idea 34's page
//                                  exports on its default preset), both computed by idea 34's committed kernel chain,
//                                  and idea 34's committed sample handoff.json, parsed unchanged
//
// Run from the bank root: node ideas/35-max-q/build-data.mjs   (then the sidecar commands it prints)
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
const here = path.dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const snap = (f) => path.join(here, 'snapshots', f);
const ASTER = '/home/user/asteroid-mining-planner';

// ---- 1. pck00010 excerpt (only when the Aster checkout is present)
const pckSrc = path.join(ASTER, 'vendor/naif/pck00010.tpc');
if (fs.existsSync(pckSrc)) {
  const lines = fs.readFileSync(pckSrc, 'utf8').split(/\r?\n/);
  const want = [];
  lines.forEach((l, i) => { if (/BODY399_(RADII|PM|POLE_RA|POLE_DEC)\s*=/.test(l)) want.push(`${String(i + 1).padStart(5)}: ${l}`); });
  fs.writeFileSync(snap('pck00010-earth.txt'), '# Excerpt of vendor/naif/pck00010.tpc (Aster), every line assigning BODY399_RADII, _PM, _POLE_RA, _POLE_DEC,\n# prefixed with its line number. Units in pck00010: radii km; PM = W0 (deg), rate (deg/day), 0.\n' + want.join('\n') + '\n');
}

// ---- 2. earth.js from the three verbatim texts
const dv = fs.readFileSync(snap('aster-delta-v.ts.txt'), 'utf8');
const fe = fs.readFileSync(snap('aster-feasibility.ts.txt'), 'utf8');
const pck = fs.readFileSync(snap('pck00010-earth.txt'), 'utf8');
const num = (s) => Number(s.replace(/_/g, ''));
const mu = num(/EARTH_MU_KM3_PER_S2\s*=\s*([\d_.]+)/.exec(dv)[1]);
const radii = /3362:\s*BODY399_RADII\s*=\s*\(\s*([\d.]+)\s+([\d.]+)\s+([\d.]+)/.exec(pck);
const pm = /BODY399_PM\s*=\s*\(\s*([\d.]+)\s+([\d.]+)/.exec(pck);
function site(name) {
  const blk = new RegExp('export const ' + name + ': LaunchSite = \\{([\\s\\S]*?)\\};').exec(fe)[1];
  const f = (k) => Number(new RegExp(k + ':\\s*([\\d.]+)').exec(blk)[1]);
  const label = /name:\s*'([^']+)'/.exec(blk)[1];
  return { name: label, latitudeDeg: f('latitudeDeg'), iMinDeg: f('iMinDeg'), iMaxDeg: f('iMaxDeg') };
}
const cape = site('CAPE_CANAVERAL'), vafb = site('VANDENBERG_SFB');
// azimuth corridors are stated in feasibility.ts's comments: "Azimuths 35-120 deg" and "Azimuths 158-201 deg"
const az = [...fe.matchAll(/Azimuths (\d+)-(\d+) deg/g)].map((m) => [Number(m[1]), Number(m[2])]);
cape.azimuthCorridorDeg = az[0]; vafb.azimuthCorridorDeg = az[1];
const E = {
  mu_m3_s2: mu * 1e9, mu_source: 'Aster src/v2/porkchop/delta-v.ts EARTH_MU_KM3_PER_S2 = ' + mu + ' km^3/s^2 (snapshots/aster-delta-v.ts.txt)',
  radius_m: Number(radii[1]) * 1000, radius_source: 'Aster vendor/naif/pck00010.tpc line 3362 BODY399_RADII a = ' + radii[1] + ' km (snapshots/pck00010-earth.txt); Aster src/v2/core/constants/README.md uses the same a as Earth\'s mean equatorial radius',
  rotation_deg_per_day: Number(pm[2]), omega_rad_s: Number(pm[2]) * Math.PI / 180 / 86400,
  omega_source: 'Aster vendor/naif/pck00010.tpc BODY399_PM rate ' + pm[2] + ' deg/day (snapshots/pck00010-earth.txt), over a day of 86400 s',
  sites: { 'cape-canaveral': cape, vandenberg: vafb },
  sites_source: 'Aster src/v2/core/lambert/feasibility.ts CAPE_CANAVERAL and VANDENBERG_SFB, azimuth corridors from its comments (snapshots/aster-feasibility.ts.txt)',
};
fs.writeFileSync(snap('earth.js'), `/* GENERATED by ideas/35-max-q/build-data.mjs from snapshots/aster-delta-v.ts.txt, snapshots/pck00010-earth.txt and
 * snapshots/aster-feasibility.ts.txt (verbatim Aster files at 62ddb17); do not edit. Classic script (window.MaxQEarth)
 * and require(). SI units. */
(function (root) {
  var D = ${JSON.stringify(E, null, 2).replace(/\n/g, '\n  ')};
  if (typeof module === 'object' && module.exports) module.exports = D;
  else root.MaxQEarth = D;
})(typeof self !== 'undefined' ? self : this);
`);

// ---- 3 and 4. idea 34's preset engines and its AS-512 handoff, from idea 34's committed kernel chain
const L = require(path.join(here, '..', '34-stack', 'load.cjs'));
const S = L.S;
const recs = {};
S.PRESET_ENGINES.forEach((id) => { recs[id] = S.engineFromPreset(id); });
const dummy = { id: 'custom', label: 'all presets', payload: { mass: 1000, label: 'Payload', source: 'user input' },
  stages: S.PRESET_ENGINES.map((id) => ({ label: id, engine: id, count: 1, dry: 1000, remaining: 0, burns: [{ propellant: 1000, shed: 0, coast: 0, jettisons: [], engineOut: [] }] })) };
const hAll = S.makeHandoff(dummy, recs, S.evaluate(dummy, recs), { produced: '2026-10-31T12:00:00Z' });
const veh = S.fromAS512(L.AS512), eng = S.as512Engines();
const hAs = S.makeHandoff(veh, eng, S.evaluate(veh, eng), { produced: '2026-10-31T12:00:00Z' });
const h34 = JSON.parse(fs.readFileSync(path.join(here, '..', '34-stack', 'handoff.json'), 'utf8'));
// one classic script for the page (file:// cannot fetch JSON); the body between the markers is plain JSON
fs.writeFileSync(snap('data-json.js'), '/* GENERATED by ideas/35-max-q/build-data.mjs; do not edit. Idea 34\'s data as a classic script (window.MAXQ_DATA) and\n' +
  ' * require(): engines34 = idea 34\'s five preset engines in its handoff format (engineFromPreset), as512 = idea 34\'s handoff for\n' +
  ' * Saturn V AS-512 as flown (makeHandoff(fromAS512)), sample34 = idea 34\'s committed handoff.json, parsed unchanged. */\n' +
  '(function (root) {\n  var D = /*JSON*/' + JSON.stringify({ engines34: hAll.inputs.engines, as512: hAs, sample34: h34 }) + '/*END*/;\n' +
  '  if (typeof module === \'object\' && module.exports) module.exports = D;\n  else root.MAXQ_DATA = D;\n})(typeof self !== \'undefined\' ? self : this);\n');
console.log('wrote pck00010-earth.txt, earth.js, data-json.js (' + Object.keys(hAll.inputs.engines).length + ' engines; AS-512 dv ' + hAs.outputs.delta_v_ideal.value.toFixed(3) + ' m/s; idea 34 sample from ' + h34.from + ')');
console.log('sidecars:');
console.log('  node tools/snapshot.mjs ' + ASTER + ' vendor/naif/pck00010.tpc ideas/35-max-q/snapshots/pck00010-earth.txt --sidecar-only --note "derived by build-data.mjs: every BODY399_RADII/PM/POLE line, with line numbers"');
console.log('  node tools/snapshot.mjs ' + ASTER + ' src/v2/porkchop/delta-v.ts ideas/35-max-q/snapshots/earth.js --sidecar-only --note "derived by build-data.mjs: GM from delta-v.ts, radius and rotation from pck00010 (pck00010-earth.txt), sites from feasibility.ts"');
console.log('  node tools/snapshot.mjs /home/user/Aster-Idea-Bank ideas/34-stack/handoff.json ideas/35-max-q/snapshots/data-json.js --sidecar-only --note "derived by build-data.mjs: idea 34 handoff.json parsed unchanged (sample34), and from idea 34 committed kernel its AS-512 handoff (as512) and five preset engines (engines34)"');
