#!/usr/bin/env node
// Writes oracle/cases.json: the flights the independent Python oracle (oracle/ascent_oracle.py) re-flies. Each case is
// a vehicle (an idea 34 handoff in snapshots/data-json.js, by key) and a complete flight plan; the solved angles (kick, upper-stage
// pitch) are solved here by this module's kernel once and then frozen in the file, so both sides fly the same plan.
// Run from the bank root: node ideas/35-max-q/oracle/build-cases.mjs
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
const here = path.dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const L = require(path.join(here, '..', 'load.cjs'));
const A = L.A;

function as512(cal, extra) {
  const v = A.vehicleFromHandoff(L.H34AS512);
  const p = A.defaultPlan(v.vehicle);
  if (cal) p.flowScale = [A.as512FlowScale(v.engines), 1, 1];
  Object.assign(p, extra || {});
  p.kickDeg = A.solveKick(v.vehicle, v.engines, p, L.T512.cutoff.sicOeco.fpa).kickDeg;
  if (p.upper.mode !== 'gravity') { const s = A.solveInsertion(v.vehicle, v.engines, p); if (s.pitchDeg != null) p.upper = Object.assign({}, p.upper, { startDeg: s.pitchDeg }); }
  return p;
}
const cases = [
  { name: 'as512-flight-average', note: 'AS-512 as flown, F-1 flow scaled to the flight average, kick solved for Table 4-2\'s cutoff angle, linear upper-stage pitch to 0 deg solved for a level burnout', data: 'as512', plan: as512(true) },
  { name: 'as512-bucket-total', note: 'AS-512 with idea 33\'s F-1 unscaled, an 80 % throttle bucket from 50 to 90 s, the power-off total axial force, upper stages held at 20 deg', data: 'as512',
    plan: Object.assign(as512(false, { throttle: { start: 50, end: 90, level: 0.8 }, drag: 'total' }), { upper: { mode: 'hold', startDeg: 20, endDeg: 0 } }) },
  { name: 'sample-34-polar', note: 'Idea 34\'s sample handoff from Vandenberg due south (azimuth 180), 4 m diameter, kick 1 deg, upper stage on the gravity turn', data: 'sample34',
    plan: (() => { const v = A.vehicleFromHandoff(L.H34); return Object.assign(A.defaultPlan(v.vehicle), { site: { id: 'vandenberg', label: L.EARTH.sites.vandenberg.name, latitudeDeg: L.EARTH.sites.vandenberg.latitudeDeg, source: L.EARTH.sites_source }, azimuthDeg: 180, kickDeg: 1, diameter: 4, stagingCoast: [3] }); })() },
];
fs.writeFileSync(path.join(here, 'cases.json'), JSON.stringify({ note: 'Generated by oracle/build-cases.mjs; flown by oracle/ascent_oracle.py (oracle) and ascent.js (tests).', cases }, null, 1) + '\n');
console.log('wrote cases.json:', cases.map((c) => c.name + ' kick ' + c.plan.kickDeg.toFixed(6)).join('; '));
